CREATE OR REPLACE PACKAGE BODY UCIB.PKG_VALIDATOR
AS
-- ======================
-- VALIDATE PERSONAL DATA
-- ======================
PROCEDURE SP_VALIDATE_PERSON(P_MAKE_BY IN VARCHAR2)
IS
  TYPE T_REF_CURSOR IS  REF  CURSOR;
    L_PERSON PERSONAL_DATA%ROWTYPE;
    L_REF_CURSOR T_REF_CURSOR;
    L_IS_VALID INT;
    L_VERSION_NO NUMBER;
    L_REPORTING_PERIOD DATE;
    L_EXISTS INT;
  BEGIN
    SELECT TO_DATE(VALUE,'DD-MON-YYYY') INTO L_REPORTING_PERIOD FROM REPORTING_PARAMETERS WHERE KEY = 'REPORTING_PERIOD';
    SELECT MAX(VERSION_NO)+1 INTO L_VERSION_NO FROM PERSONAL_DATA_REPORT WHERE REPORTING_PERIOD = L_REPORTING_PERIOD;
    IF L_VERSION_NO IS NULL THEN L_VERSION_NO := 1; END IF;

    OPEN L_REF_CURSOR FOR SELECT * FROM PERSONAL_DATA WHERE RECORD_STATUS NOT IN ('D','R','L');
    LOOP
      FETCH
        L_REF_CURSOR
      INTO
        L_PERSON;
    EXIT
  WHEN L_REF_CURSOR % NOTFOUND;
    --DBMS_OUTPUT.PUT_LINE(L_PERSON.FI_SUBJECT_CODE);
    L_IS_VALID := 1;

    -- CHECKING RECORD TYPE EQUALS 'P'
    IF L_PERSON.RECORD_TYPE != 'P' THEN
      L_IS_VALID :=0 ;
      INSERT INTO PERSONAL_DATA_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_PERSON.FI_SUBJECT_CODE, NULL, 'INVALID RECORD TYPE', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING FI_CODE EQUAL '046'
    IF L_PERSON.FI_CODE != '046' THEN
      L_IS_VALID :=0 ;
      INSERT INTO PERSONAL_DATA_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_PERSON.FI_SUBJECT_CODE, NULL, 'INVALID FI CODE', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING IF BRANCH_CODE IS VALID CIB BRANCH CODE
    SELECT COUNT(1) INTO L_EXISTS FROM BRANCHES WHERE CIB_BRANCH_CODE = L_PERSON.BRANCH_CODE;
    IF L_EXISTS = 0 THEN
      L_IS_VALID :=0 ;
      INSERT INTO PERSONAL_DATA_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_PERSON.FI_SUBJECT_CODE, NULL, 'INVALID CIB BRANCH CODE', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING IF FI_SUBJECT_CODE IS 16 DIGITS
    IF LENGTH(L_PERSON.FI_SUBJECT_CODE) != 16 THEN
      L_IS_VALID := 0;
      INSERT INTO PERSONAL_DATA_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_PERSON.FI_SUBJECT_CODE, NULL, 'SUBJECT CODE NOT 16 DIGIT', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING PERSON NAME
    IF L_PERSON.NAME IS NULL OR LENGTH(L_PERSON.NAME) < 4 THEN
      L_IS_VALID := 0;
      INSERT INTO PERSONAL_DATA_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_PERSON.FI_SUBJECT_CODE, NULL, 'PERSON NAME INVALID', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING FATHERS NAME
    IF L_PERSON.FATHERS_NAME IS NULL OR LENGTH(L_PERSON.FATHERS_NAME) < 0 THEN
      L_IS_VALID := 0;
      INSERT INTO PERSONAL_DATA_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_PERSON.FI_SUBJECT_CODE, NULL, 'FATHERS NAME INVALID', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING MOTHERS NAME
    IF L_PERSON.MOTHERS_NAME IS NULL OR LENGTH(L_PERSON.MOTHERS_NAME) < 0 THEN
      L_IS_VALID := 0;
      INSERT INTO PERSONAL_DATA_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_PERSON.FI_SUBJECT_CODE, NULL, 'MOTHERS NAME INVALID', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING SECTOR TYPE AND SECTOR CODE
--    IF (NVL(L_PERSON.SECTOR_TYPE,0) = 0 AND NVL(L_PERSON.SECTOR_CODE,0) != 0) OR
--       (NVL(L_PERSON.SECTOR_TYPE,0) != 0 AND NVL(L_PERSON.SECTOR_CODE,0) = 0) THEN
--      L_IS_VALID := 0;
--      INSERT INTO PERSONAL_DATA_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
--      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_PERSON.FI_SUBJECT_CODE, NULL, 'SECTOR CODE AND SECTOR TYPE MUST BE FILLED TOGATHER', P_MAKE_BY, SYSDATE);
--    END IF;

    -- CHECKING SECTOR_TYPE DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM LOV_SECTOR_TYPES WHERE CODE=NVL(L_PERSON.SECTOR_TYPE,1);
    IF L_EXISTS = 0 THEN
    L_IS_VALID := 0;
      INSERT INTO PERSONAL_DATA_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_PERSON.FI_SUBJECT_CODE, NULL, 'SECTOR TYPE NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING SECTOR_CODE DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM LOV_SECTOR_CODES WHERE CODE=NVL(L_PERSON.SECTOR_CODE,113309);
    IF L_EXISTS = 0 THEN
    L_IS_VALID := 0;
      INSERT INTO PERSONAL_DATA_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_PERSON.FI_SUBJECT_CODE, NULL, 'SECTOR CODE NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING GENDER DOMAIN
    IF L_PERSON.GENDER != 'M' AND L_PERSON.GENDER != 'F' THEN
      L_IS_VALID := 0;
      INSERT INTO PERSONAL_DATA_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_PERSON.FI_SUBJECT_CODE, NULL, 'GENDER NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING DATE OF BIRTH
    IF L_PERSON.DATE_OF_BIRTH = TO_DATE('01 JAN 1800','DD MON YYYY') THEN
    L_IS_VALID := 0;
      INSERT INTO PERSONAL_DATA_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_PERSON.FI_SUBJECT_CODE, NULL, 'DATE OF BIRTH MANDATORY', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING PLACE OF BIRTH DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM LOV_DISTRICTS WHERE DISTRICT_NAME = NVL(L_PERSON.PLACE_OF_BIRTH,'~');
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO PERSONAL_DATA_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_PERSON.FI_SUBJECT_CODE, NULL, 'PLACE OF BIRTH NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING COUNTRY OF BIRTH DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM LOV_COUNTRIES WHERE CODE = NVL(L_PERSON.COUNTRY_OF_BIRTH,'~');
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO PERSONAL_DATA_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_PERSON.FI_SUBJECT_CODE, NULL, 'COUNTRY OF BIRTH NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING NATIONAL ID
    IF(L_PERSON.NATIONAL_ID_NUMBER IS NOT NULL OR LENGTH(L_PERSON.NATIONAL_ID_NUMBER)>0) THEN
      IF (LENGTH(L_PERSON.NATIONAL_ID_NUMBER) != 13 AND LENGTH(L_PERSON.NATIONAL_ID_NUMBER) != 17) OR REGEXP_INSTR(L_PERSON.NATIONAL_ID_NUMBER,'[^0123456789]') > 0  THEN
        L_IS_VALID := 0;
        INSERT INTO PERSONAL_DATA_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
        VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_PERSON.FI_SUBJECT_CODE, NULL, 'INVALID NATIONAL ID NUMBER', P_MAKE_BY, SYSDATE);
      END IF;
    END IF;

    -- CHECKING NATIONAL_ID_AVAILABLE
    IF (L_PERSON.NATIONAL_ID_NUMBER IS NULL AND L_PERSON.NATIONAL_ID_AVAILABLE = 1) OR
       (L_PERSON.NATIONAL_ID_NUMBER IS NOT NULL AND L_PERSON.NATIONAL_ID_AVAILABLE = 0) THEN
      L_IS_VALID := 0;
      INSERT INTO PERSONAL_DATA_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_PERSON.FI_SUBJECT_CODE, NULL, 'NATIONAL ID AVAIL FLAG DOES NOT MATCH VALUE', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING TIN
    IF LENGTH(L_PERSON.TIN)!= 12 OR REGEXP_INSTR(L_PERSON.TIN,'[^0123456789]') > 0 THEN
      L_IS_VALID := 0;
      INSERT INTO PERSONAL_DATA_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_PERSON.FI_SUBJECT_CODE, NULL, 'INVALID TIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING NATIONAL_ID_AVAILABLE DOMAIN
    IF L_PERSON.NATIONAL_ID_AVAILABLE != 0 AND L_PERSON.NATIONAL_ID_AVAILABLE != 1 THEN
      L_IS_VALID := 0;
      INSERT INTO PERSONAL_DATA_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_PERSON.FI_SUBJECT_CODE, NULL, 'NATIONAL ID AVAIL NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING PERMANENT ADDRESS
    IF NOT ((L_PERSON.PERMANENT_ADDRESS_STREET IS NULL AND L_PERSON.PERMANENT_ADDRESS_DISTRICT IS NULL AND L_PERSON.PERMANENT_ADDRESS_COUNTRY IS NULL) OR
       (L_PERSON.PERMANENT_ADDRESS_STREET IS NOT NULL AND L_PERSON.PERMANENT_ADDRESS_DISTRICT IS NOT NULL AND L_PERSON.PERMANENT_ADDRESS_COUNTRY IS NOT NULL)) THEN
       L_IS_VALID := 0;
      INSERT INTO PERSONAL_DATA_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_PERSON.FI_SUBJECT_CODE, NULL, 'PERMANENT ADDRESS NOT FILLED CORRECTLY', P_MAKE_BY, SYSDATE);
    END IF;

    SELECT COUNT(1) INTO L_EXISTS FROM LOV_DISTRICTS WHERE DISTRICT_NAME = NVL(L_PERSON.PERMANENT_ADDRESS_DISTRICT,'DHAKA');
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO PERSONAL_DATA_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_PERSON.FI_SUBJECT_CODE, NULL, 'PERMANENT ADDRESS DISTRICT NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    SELECT COUNT(1) INTO L_EXISTS FROM LOV_COUNTRIES WHERE CODE = NVL(L_PERSON.PERMANENT_ADDRESS_COUNTRY,'~');
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO PERSONAL_DATA_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_PERSON.FI_SUBJECT_CODE, NULL, 'PERMANENT ADDRESS COUNTRY NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING PRESENT ADDRESS
    IF NOT ((L_PERSON.PRESENT_ADDRESS_STREET IS NULL AND L_PERSON.PRESENT_ADDRESS_DISTRICT IS NULL AND L_PERSON.PRESENT_ADDRESS_COUNTRY IS NULL) OR
       (L_PERSON.PRESENT_ADDRESS_STREET IS NOT NULL AND L_PERSON.PRESENT_ADDRESS_DISTRICT IS NOT NULL AND L_PERSON.PRESENT_ADDRESS_COUNTRY IS NOT NULL)) THEN
       L_IS_VALID := 0;
      INSERT INTO PERSONAL_DATA_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_PERSON.FI_SUBJECT_CODE, NULL, 'PRESENT ADDRESS NOT FILLED CORRECTLY', P_MAKE_BY, SYSDATE);
    END IF;

    SELECT COUNT(1) INTO L_EXISTS FROM LOV_DISTRICTS WHERE DISTRICT_NAME = NVL(L_PERSON.PRESENT_ADDRESS_DISTRICT,'DHAKA');
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO PERSONAL_DATA_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_PERSON.FI_SUBJECT_CODE, NULL, 'PRESENT ADDRESS DISTRICT NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    SELECT COUNT(1) INTO L_EXISTS FROM LOV_COUNTRIES WHERE CODE = NVL(L_PERSON.PRESENT_ADDRESS_COUNTRY,'BD');
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO PERSONAL_DATA_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_PERSON.FI_SUBJECT_CODE, NULL, 'PRESENT ADDRESS COUNTRY NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING BUSINESS ADDRESS
    IF NOT ((L_PERSON.BUSINESS_ADDRESS_STREET IS NULL AND L_PERSON.BUSINESS_ADDRESS_DISTRICT IS NULL AND L_PERSON.BUSINESS_ADDRESS_COUNTRY IS NULL) OR
       (L_PERSON.BUSINESS_ADDRESS_STREET IS NOT NULL AND L_PERSON.BUSINESS_ADDRESS_DISTRICT IS NOT NULL AND L_PERSON.BUSINESS_ADDRESS_COUNTRY IS NOT NULL)) THEN
       L_IS_VALID := 0;
      INSERT INTO PERSONAL_DATA_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_PERSON.FI_SUBJECT_CODE, NULL, 'BUSINESS ADDRESS NOT FILLED CORRECTLY', P_MAKE_BY, SYSDATE);
    END IF;

    SELECT COUNT(1) INTO L_EXISTS FROM LOV_DISTRICTS WHERE DISTRICT_NAME = NVL(L_PERSON.BUSINESS_ADDRESS_DISTRICT,'DHAKA');
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO PERSONAL_DATA_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_PERSON.FI_SUBJECT_CODE, NULL, 'BUSINESS ADDRESS DISTRICT NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    SELECT COUNT(1) INTO L_EXISTS FROM LOV_COUNTRIES WHERE CODE = NVL(L_PERSON.BUSINESS_ADDRESS_COUNTRY,'BD');
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO PERSONAL_DATA_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_PERSON.FI_SUBJECT_CODE, NULL, 'BUSINESS ADDRESS COUNTRY NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    --CHECKING ID
    IF (L_PERSON.ID_TYPE IS NOT NULL OR L_PERSON.ID_NUMBER IS NOT NULL OR L_PERSON.ID_ISSUE_DATE IS NOT NULL OR L_PERSON.ID_ISSUE_COUNTRY IS NOT NULL) AND
       (L_PERSON.ID_TYPE IS NULL OR L_PERSON.ID_NUMBER IS NULL OR L_PERSON.ID_ISSUE_DATE IS NULL OR L_PERSON.ID_ISSUE_COUNTRY IS NULL)
    THEN
      L_IS_VALID := 0;
      INSERT INTO PERSONAL_DATA_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_PERSON.FI_SUBJECT_CODE, NULL, 'MISSING INFORMATION IN ID', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING ID TYPE DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM LOV_ID_TYPES WHERE CODE = NVL(L_PERSON.ID_TYPE,'1');
    IF L_EXISTS = 0 THEN
        L_IS_VALID := 0;
      INSERT INTO PERSONAL_DATA_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_PERSON.FI_SUBJECT_CODE, NULL, 'ID TYPE NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING ID ISSUE COUNTRY DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM LOV_COUNTRIES WHERE CODE = NVL(L_PERSON.ID_ISSUE_COUNTRY,'BD');
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO PERSONAL_DATA_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_PERSON.FI_SUBJECT_CODE, NULL, 'ID ISSUE COUNTRY NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING NATIONAL ID OR ID AVAILABILITY
    IF L_PERSON.NATIONAL_ID_NUMBER IS NULL AND L_PERSON.ID_NUMBER IS NULL THEN
      L_IS_VALID := 0;
      INSERT INTO PERSONAL_DATA_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_PERSON.FI_SUBJECT_CODE, NULL, 'NATIONAL ID OR ANY OTHER ID MUST BE GIVEN', P_MAKE_BY, SYSDATE);
    END IF;

    IF L_IS_VALID = 1 THEN
      INSERT INTO PERSONAL_DATA_REPORT(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD, L_PERSON.FI_SUBJECT_CODE, P_MAKE_BY, SYSDATE);
      UPDATE PERSONAL_DATA SET RECORD_STATUS = 'U' WHERE FI_SUBJECT_CODE = L_PERSON.FI_SUBJECT_CODE;
    ELSE
      UPDATE PERSONAL_DATA SET RECORD_STATUS = 'E' WHERE FI_SUBJECT_CODE = L_PERSON.FI_SUBJECT_CODE;
    END IF;

  END LOOP;
END SP_VALIDATE_PERSON;

-- ====================
-- VALIDATE INSTITUTION
-- ====================
PROCEDURE SP_VALIDATE_INSTITUTION(P_MAKE_BY IN VARCHAR2)
  IS
  TYPE T_REF_CURSOR IS REF CURSOR;

  L_INSTITUTION INSTITUTIONS%ROWTYPE;
  L_REF_CURSOR T_REF_CURSOR;
  L_IS_VALID INT;
  L_VERSION_NO NUMBER;
  L_REPORTING_PERIOD DATE;
  L_EXISTS INT;
  BEGIN
    SELECT TO_DATE(VALUE,'DD-MON-YYYY') INTO L_REPORTING_PERIOD FROM REPORTING_PARAMETERS WHERE KEY = 'REPORTING_PERIOD';
    SELECT MAX(VERSION_NO)+1 INTO L_VERSION_NO FROM INSTITUTION_REPORT WHERE REPORTING_PERIOD = L_REPORTING_PERIOD;
    IF L_VERSION_NO IS NULL THEN L_VERSION_NO := 1; END IF;

    OPEN L_REF_CURSOR FOR SELECT * FROM INSTITUTIONS WHERE RECORD_STATUS NOT IN ('D','R','L');
    LOOP
      FETCH
        L_REF_CURSOR
      INTO
        L_INSTITUTION;
    EXIT WHEN L_REF_CURSOR % NOTFOUND;
    --DBMS_OUTPUT.PUT_LINE(L_PERSON.FI_SUBJECT_CODE);
    L_IS_VALID := 1;

    IF L_INSTITUTION.RECORD_TYPE != 'C' AND L_INSTITUTION.RECORD_TYPE != 'I' THEN
      L_IS_VALID := 0;
      INSERT INTO INSTITUTION_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_INSTITUTION.FI_SUBJECT_CODE, NULL, 'RECORD TYPE NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    IF L_INSTITUTION.FI_CODE != '046' THEN
      L_IS_VALID := 0;
      INSERT INTO INSTITUTION_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_INSTITUTION.FI_SUBJECT_CODE, NULL, 'FI CODE NOT CORRECT', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING TRADE NAME
    IF L_INSTITUTION.TRADE_NAME IS NULL OR LENGTH(L_INSTITUTION.TRADE_NAME) < 4 THEN
      L_IS_VALID := 0;
      INSERT INTO INSTITUTION_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_INSTITUTION.FI_SUBJECT_CODE, NULL, 'TRADE NAME IS INVALID', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING CIB BRANCH_CODE
    SELECT COUNT(1) INTO L_EXISTS FROM BRANCHES WHERE CIB_BRANCH_CODE = L_INSTITUTION.BRANCH_CODE;
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO INSTITUTION_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_INSTITUTION.FI_SUBJECT_CODE, NULL, 'BRANCH CODE NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING FI_SUBJECT_CODE
    IF LENGTH(L_INSTITUTION.FI_SUBJECT_CODE) != 16 THEN
      L_IS_VALID := 0;
      INSERT INTO INSTITUTION_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_INSTITUTION.FI_SUBJECT_CODE, NULL, 'FI SUBJECT CODE NOT 16 DIGIT', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING SECTOR CODE AND SECTOR TYPE
--    IF (L_INSTITUTION.SECTOR_TYPE IS NOT NULL OR L_INSTITUTION.SECTOR_CODE IS NOT NULL) AND
--       (L_INSTITUTION.SECTOR_TYPE IS NULL OR L_INSTITUTION.SECTOR_CODE IS NULL) THEN
--      L_IS_VALID := 0;
--      INSERT INTO INSTITUTION_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
--      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_INSTITUTION.FI_SUBJECT_CODE, NULL, 'SECTOR CODE AND SECTOR TYPE MUST BE FILLED TOGATHER', P_MAKE_BY, SYSDATE);
--    END IF;

    -- CHECKING SECTOR TYPE DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM LOV_SECTOR_TYPES WHERE CODE = NVL(L_INSTITUTION.SECTOR_TYPE,'1');
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO INSTITUTION_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_INSTITUTION.FI_SUBJECT_CODE, NULL, 'SECTOR TYPE NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING SECTOR CODE DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM LOV_SECTOR_CODES WHERE CODE = NVL(L_INSTITUTION.SECTOR_CODE,'113309');
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO INSTITUTION_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_INSTITUTION.FI_SUBJECT_CODE, NULL, 'SECTOR CODE NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING LEGAL FORM DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM LOV_INSTITUTION_LEGAL_FORMS WHERE CODE = NVL(L_INSTITUTION.LEGAL_FORM,'1');
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO INSTITUTION_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_INSTITUTION.FI_SUBJECT_CODE, NULL, 'LEGAL FORM NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING REGISTRATION NUMBER & DATE (RJSC)
    IF (L_INSTITUTION.REGISTRATION_NUMBER_RJSC IS NOT NULL OR L_INSTITUTION.REGISTRATION_DATE_RJSC IS NOT NULL) AND
       (L_INSTITUTION.REGISTRATION_NUMBER_RJSC IS NULL OR L_INSTITUTION.REGISTRATION_DATE_RJSC IS NULL) THEN
      L_IS_VALID := 0;
      INSERT INTO INSTITUTION_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_INSTITUTION.FI_SUBJECT_CODE, NULL, 'RJSC DATA INCONSISTENT', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING TIN
    IF LENGTH(L_INSTITUTION.TIN)!= 12 OR REGEXP_INSTR(L_INSTITUTION.TIN,'[^0123456789]') > 0 THEN
      L_IS_VALID := 0;
      INSERT INTO INSTITUTION_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_INSTITUTION.FI_SUBJECT_CODE, NULL, 'INVALID TIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING BUSINESS ADDRESS
    IF NOT ((L_INSTITUTION.BUSINESS_ADDRESS_STREET IS NULL AND L_INSTITUTION.BUSINESS_ADDRESS_DISTRICT IS NULL AND L_INSTITUTION.BUSINESS_ADDRESS_COUNTRY IS NULL) OR
       (L_INSTITUTION.BUSINESS_ADDRESS_STREET IS NOT NULL AND L_INSTITUTION.BUSINESS_ADDRESS_DISTRICT IS NOT NULL AND L_INSTITUTION.BUSINESS_ADDRESS_COUNTRY IS NOT NULL)) THEN
       L_IS_VALID := 0;
      INSERT INTO INSTITUTION_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_INSTITUTION.FI_SUBJECT_CODE, NULL, 'BUSINESS ADDRESS NOT FILLED CORRECTLY', P_MAKE_BY, SYSDATE);
    END IF;

    SELECT COUNT(1) INTO L_EXISTS FROM LOV_DISTRICTS WHERE DISTRICT_NAME = NVL(L_INSTITUTION.BUSINESS_ADDRESS_DISTRICT,'DHAKA');
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO INSTITUTION_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_INSTITUTION.FI_SUBJECT_CODE, NULL, 'BUSINESS ADDRESS DISTRICT NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    SELECT COUNT(1) INTO L_EXISTS FROM LOV_COUNTRIES WHERE CODE = NVL(L_INSTITUTION.BUSINESS_ADDRESS_COUNTRY,'BD');
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO INSTITUTION_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_INSTITUTION.FI_SUBJECT_CODE, NULL, 'BUSINESS ADDRESS COUNTRY NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

     -- CHECKING FACTORY ADDRESS
    IF NOT ((L_INSTITUTION.FACTORY_ADDRESS_STREET IS NULL AND L_INSTITUTION.FACTORY_ADDRESS_DISTRICT IS NULL AND L_INSTITUTION.FACTORY_ADDRESS_COUNTRY IS NULL) OR
       (L_INSTITUTION.FACTORY_ADDRESS_STREET IS NOT NULL AND L_INSTITUTION.FACTORY_ADDRESS_DISTRICT IS NOT NULL AND L_INSTITUTION.FACTORY_ADDRESS_COUNTRY IS NOT NULL)) THEN
       L_IS_VALID := 0;
      INSERT INTO INSTITUTION_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_INSTITUTION.FI_SUBJECT_CODE, NULL, 'FACTORY ADDRESS NOT FILLED CORRECTLY', P_MAKE_BY, SYSDATE);
    END IF;

    SELECT COUNT(1) INTO L_EXISTS FROM LOV_DISTRICTS WHERE DISTRICT_NAME = NVL(L_INSTITUTION.FACTORY_ADDRESS_DISTRICT,'DHAKA');
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO INSTITUTION_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_INSTITUTION.FI_SUBJECT_CODE, NULL, 'FACTORY ADDRESS DISTRICT NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    SELECT COUNT(1) INTO L_EXISTS FROM LOV_COUNTRIES WHERE CODE = NVL(L_INSTITUTION.FACTORY_ADDRESS_COUNTRY,'BD');
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO INSTITUTION_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_INSTITUTION.FI_SUBJECT_CODE, NULL, 'FACTORY ADDRESS COUNTRY NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- FOR PROPRIERTORSHIP CHECK IF OWNER LINK IS CREATED
    IF L_INSTITUTION.RECORD_TyPE = 'I' THEN
      SELECT COUNT(1) INTO L_EXISTS FROM INSTITUTION_OWNER_LINKS A JOIN VW_SUBJECTS B ON A.OWNER_FI_SUBJECT_CODE = B.FI_SUBJECT_CODE WHERE INSTITUTION_FI_SUBJECT_CODE = L_INSTITUTION.FI_SUBJECT_CODE AND ROLE = '10' AND A.RECORD_STATUS <> 'D';
      IF L_EXISTS = 0 THEN
        L_IS_VALID := 0;
        INSERT INTO INSTITUTION_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
        VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_INSTITUTION.FI_SUBJECT_CODE, '10-530', 'PROPRIETOR IS NOT LINK WITH ANY OWNER', P_MAKE_BY, SYSDATE);
      ELSIF L_EXISTS > 1 THEN
        INSERT INTO INSTITUTION_ERROR(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
        VALUES(L_VERSION_NO, L_REPORTING_PERIOD,L_INSTITUTION.FI_SUBJECT_CODE, '10-531', 'PROPRIETOR IS LINKED WITH MORE THEN ONE OWNER', P_MAKE_BY, SYSDATE);
      END IF;
    END IF;


    IF L_IS_VALID = 1 THEN
      INSERT INTO INSTITUTION_REPORT(VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, MAKE_BY, MAKE_DATE)
      VALUES(L_VERSION_NO, L_REPORTING_PERIOD, L_INSTITUTION.FI_SUBJECT_CODE, P_MAKE_BY, SYSDATE);
      UPDATE INSTITUTIONS SET RECORD_STATUS = 'U' WHERE FI_SUBJECT_CODE = L_INSTITUTION.FI_SUBJECT_CODE;
    ELSE
      UPDATE INSTITUTIONS SET RECORD_STATUS = 'E' WHERE FI_SUBJECT_CODE = L_INSTITUTION.FI_SUBJECT_CODE;
    END IF;
    END LOOP;

END SP_VALIDATE_INSTITUTION;

PROCEDURE SP_VALIDATE_OWNER_LINK(P_MAKE_BY IN VARCHAR2)
AS
  TYPE T_REF_CURSOR IS REF CURSOR;

  L_LINK INSTITUTION_OWNER_LINKS%ROWTYPE;
  L_REF_CURSOR T_REF_CURSOR;
  L_IS_VALID INT;
  L_VERSION_NO NUMBER;
  L_REPORTING_PERIOD DATE;
  L_EXISTS INT;
BEGIN
  SELECT TO_DATE(VALUE,'DD-MON-YYYY') INTO L_REPORTING_PERIOD FROM REPORTING_PARAMETERS WHERE KEY = 'REPORTING_PERIOD';
    SELECT MAX(VERSION_NO)+1 INTO L_VERSION_NO FROM OWNER_LINK_REPORT WHERE REPORTING_PERIOD = L_REPORTING_PERIOD;
    IF L_VERSION_NO IS NULL THEN L_VERSION_NO := 1; END IF;

    OPEN L_REF_CURSOR FOR SELECT * FROM INSTITUTION_OWNER_LINKS WHERE RECORD_STATUS NOT IN ('D','R');
    LOOP
      FETCH L_REF_CURSOR INTO L_LINK;
      EXIT WHEN L_REF_CURSOR % NOTFOUND;

      L_IS_VALID := 1;

      -- CHECK RECORD TYPE DOMAIN
      IF L_LINK.RECORD_TYPE != 'L' THEN
        L_IS_VALID := 0;
        INSERT INTO OWNER_LINK_ERROR (VERSION_NO, REPORTING_PERIOD, INSTITUTION_FI_SUBJECT_CODE, OWNER_FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
        VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_LINK.INSTITUTION_FI_SUBJECT_CODE, L_LINK.OWNER_FI_SUBJECT_CODE, NULL, 'RECORD TYPE NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
      END IF;

      -- CHECK FI CODE
      IF L_LINK.FI_CODE != '046' THEN
        L_IS_VALID := 0;
        INSERT INTO OWNER_LINK_ERROR (VERSION_NO, REPORTING_PERIOD, INSTITUTION_FI_SUBJECT_CODE, OWNER_FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
        VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_LINK.INSTITUTION_FI_SUBJECT_CODE, L_LINK.OWNER_FI_SUBJECT_CODE, NULL, 'FI CODE NOT CORRECT', P_MAKE_BY, SYSDATE);
      END IF;

      -- CHECK CIB BRANCH CODE DOMAIN
      SELECT COUNT(1) INTO L_EXISTS FROM BRANCHES WHERE CIB_BRANCH_CODE = L_LINK.BRANCH_CODE;
      IF L_EXISTS = 0 THEN
        L_IS_VALID := 0;
        INSERT INTO OWNER_LINK_ERROR (VERSION_NO, REPORTING_PERIOD, INSTITUTION_FI_SUBJECT_CODE, OWNER_FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
        VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_LINK.INSTITUTION_FI_SUBJECT_CODE, L_LINK.OWNER_FI_SUBJECT_CODE, NULL, 'BRANCH CODE NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
      END IF;

      -- CHECKING ROLE DOMAIN
      SELECT COUNT(1) INTO L_EXISTS FROM LOV_OWNER_TYPES WHERE CODE = NVL(L_LINK.ROLE,'~');
      IF L_EXISTS = 0 THEN
        INSERT INTO OWNER_LINK_ERROR (VERSION_NO, REPORTING_PERIOD, INSTITUTION_FI_SUBJECT_CODE, OWNER_FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
        VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_LINK.INSTITUTION_FI_SUBJECT_CODE, L_LINK.OWNER_FI_SUBJECT_CODE, NULL, 'OWNER ROLE NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
        -- UPDATE OWNER LINK FLAG TO ERROR
        UPDATE INSTITUTION_OWNER_LINKS SET RECORD_STATUS = 'E' WHERE INSTITUTION_FI_SUBJECT_CODE = L_LINK.INSTITUTION_FI_SUBJECT_CODE AND OWNER_FI_SUBJECT_CODE = L_LINK.OWNER_FI_SUBJECT_CODE;
      END IF;

      -- CHECKING INSTITUTIONS DOMAIN
      SELECT COUNT(1) INTO L_EXISTS FROM INSTITUTIONS WHERE FI_SUBJECT_CODE = L_LINK.INSTITUTION_FI_SUBJECT_CODE;
      IF L_EXISTS = 0  THEN
        L_IS_VALID := 0;
        INSERT INTO OWNER_LINK_ERROR (VERSION_NO, REPORTING_PERIOD, INSTITUTION_FI_SUBJECT_CODE, OWNER_FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
        VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_LINK.INSTITUTION_FI_SUBJECT_CODE, L_LINK.OWNER_FI_SUBJECT_CODE, NULL, 'INSTITUTION NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
      END IF;

      -- CHECKING OWNERS DOMAIN
      SELECT COUNT(1) INTO L_EXISTS FROM VW_SUBJECTS WHERE FI_SUBJECT_CODE = L_LINK.OWNER_FI_SUBJECT_CODE;
      IF L_EXISTS = 0  THEN
        L_IS_VALID := 0;
        INSERT INTO OWNER_LINK_ERROR (VERSION_NO, REPORTING_PERIOD, INSTITUTION_FI_SUBJECT_CODE, OWNER_FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
        VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_LINK.INSTITUTION_FI_SUBJECT_CODE, L_LINK.OWNER_FI_SUBJECT_CODE, NULL, 'OWNER NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
      END IF;


      -- CHECK INSTITUTION FI_SUBJECT_CODE ANOMALY
      SELECT COUNT(1) INTO L_EXISTS FROM INSTITUTION_ERROR WHERE FI_SUBJECT_CODE = L_LINK.INSTITUTION_FI_SUBJECT_CODE AND REPORTING_PERIOD = L_REPORTING_PERIOD AND VERSION_NO = L_VERSION_NO;
      IF L_EXISTS > 0 THEN
        L_IS_VALID := 0;
        INSERT INTO OWNER_LINK_ERROR (VERSION_NO, REPORTING_PERIOD, INSTITUTION_FI_SUBJECT_CODE, OWNER_FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
        VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_LINK.INSTITUTION_FI_SUBJECT_CODE, L_LINK.OWNER_FI_SUBJECT_CODE, NULL, 'INSTITUTION IN ANOMALY', P_MAKE_BY, SYSDATE);

        -- MOVING OWNER TO ERROR
        IF SUBSTR(L_LINK.OWNER_FI_SUBJECT_CODE,1,1) = 'P' THEN
          INSERT INTO PERSONAL_DATA_ERROR (VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
          VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_LINK.OWNER_FI_SUBJECT_CODE, NULL, 'INSTITUTION "'||L_LINK.INSTITUTION_FI_SUBJECT_CODE||'" IN ANOMALY', P_MAKE_BY, SYSDATE);
          -- REMOVE OWNER FROM REPORT
          DELETE FROM PERSONAL_DATA_REPORT WHERE VERSION_NO = L_VERSION_NO AND REPORTING_PERIOD = L_REPORTING_PERIOD AND FI_SUBJECT_CODE = L_LINK.OWNER_FI_SUBJECT_CODE;
        ELSE
          INSERT INTO INSTITUTION_ERROR (VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
          VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_LINK.OWNER_FI_SUBJECT_CODE, NULL, 'INSTITUTION "'||L_LINK.INSTITUTION_FI_SUBJECT_CODE||'" IN ANOMALY', P_MAKE_BY, SYSDATE);
          -- REMOVE OWNER FROM REPORT
          DELETE FROM INSTITUTION_REPORT WHERE  VERSION_NO = L_VERSION_NO AND REPORTING_PERIOD = L_REPORTING_PERIOD AND FI_SUBJECT_CODE = L_LINK.OWNER_FI_SUBJECT_CODE;
        END IF;

      END IF;

      -- CHECKING OWNER ANOMALY
      SELECT SUM(CNT) INTO L_EXISTS FROM
      (SELECT COUNT(1) CNT FROM INSTITUTION_ERROR WHERE FI_SUBJECT_CODE = L_LINK.OWNER_FI_SUBJECT_CODE AND REPORTING_PERIOD = L_REPORTING_PERIOD AND VERSION_NO = L_VERSION_NO
       UNION ALL
       SELECT COUNT(1) CNT FROM PERSONAL_DATA_ERROR WHERE FI_SUBJECT_CODE = L_LINK.OWNER_FI_SUBJECT_CODE AND REPORTING_PERIOD = L_REPORTING_PERIOD AND VERSION_NO = L_VERSION_NO);
      IF L_EXISTS > 0 THEN
        L_IS_VALID := 0;
        INSERT INTO OWNER_LINK_ERROR (VERSION_NO, REPORTING_PERIOD, INSTITUTION_FI_SUBJECT_CODE, OWNER_FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
        VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_LINK.INSTITUTION_FI_SUBJECT_CODE, L_LINK.OWNER_FI_SUBJECT_CODE, NULL, 'OWNER IN ANOMALY', P_MAKE_BY, SYSDATE);

        -- REMOVING INSTITUTION FROM REPORT
        INSERT INTO INSTITUTION_ERROR (VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
        VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_LINK.INSTITUTION_FI_SUBJECT_CODE, NULL, 'OWNER "'||L_LINK.OWNER_FI_SUBJECT_CODE||'" IN ANOMALY', P_MAKE_BY, SYSDATE);
        DELETE FROM INSTITUTION_REPORT WHERE VERSION_NO = L_VERSION_NO AND REPORTING_PERIOD = L_REPORTING_PERIOD AND FI_SUBJECT_CODE = L_LINK.INSTITUTION_FI_SUBJECT_CODE;
      END IF;

      IF L_IS_VALID = 1 THEN
        INSERT INTO OWNER_LINK_REPORT(VERSION_NO, REPORTING_PERIOD, INSTITUTION_FI_SUBJECT_CODE, OWNER_FI_SUBJECT_CODE, MAKE_BY, MAKE_DATE)
        VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_LINK.INSTITUTION_FI_SUBJECT_CODE, L_LINK.OWNER_FI_SUBJECT_CODE, P_MAKE_BY, SYSDATE);
        UPDATE INSTITUTION_OWNER_LINKS SET RECORD_STATUS = 'U' WHERE INSTITUTION_FI_SUBJECT_CODE = L_LINK.INSTITUTION_FI_SUBJECT_CODE AND OWNER_FI_SUBJECT_CODE = L_LINK.OWNER_FI_SUBJECT_CODE;
      ELSE
        UPDATE INSTITUTION_OWNER_LINKS SET RECORD_STATUS = 'E' WHERE INSTITUTION_FI_SUBJECT_CODE = L_LINK.INSTITUTION_FI_SUBJECT_CODE AND OWNER_FI_SUBJECT_CODE = L_LINK.OWNER_FI_SUBJECT_CODE;
      END IF;
    END LOOP;


END SP_VALIDATE_OWNER_LINK;

-- =========================================
-- PROCEDURE TO VALIDATE INSTALMENT CONTRACT
-- =========================================
PROCEDURE SP_VALIDATE_INST_CONTRACT(P_MAKE_BY IN VARCHAR2)
AS
  TYPE T_REF_CURSOR IS REF CURSOR;

  L_CONTRACT INSTALMENT_CONTRACTS%ROWTYPE;
  L_REF_CURSOR T_REF_CURSOR;
  L_IS_VALID INT;
  L_VERSION_NO NUMBER;
  L_REPORTING_PERIOD DATE;
  L_EXISTS INT;
BEGIN
  SELECT TO_DATE(VALUE,'DD-MON-YYYY') INTO L_REPORTING_PERIOD FROM REPORTING_PARAMETERS WHERE KEY = 'REPORTING_PERIOD';
  SELECT MAX(VERSION_NO)+1 INTO L_VERSION_NO FROM INSTALMENT_CONTRACT_REPORT WHERE REPORTING_PERIOD = L_REPORTING_PERIOD;

  IF L_VERSION_NO IS NULL THEN L_VERSION_NO := 1; END IF;

  OPEN L_REF_CURSOR FOR SELECT * FROM INSTALMENT_CONTRACTS WHERE RECORD_STATUS not in ('D', 'T') and STARTING_DATE <= L_REPORTING_PERIOD; --deleted or terminated
  LOOP
    FETCH L_REF_CURSOR INTO L_CONTRACT;
    EXIT WHEN L_REF_CURSOR % NOTFOUND;

    L_IS_VALID := 1;

    -- CHECKING RECORD TYPE DOMAIN
    IF L_CONTRACT.RECORD_TYPE != 'D' THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'RECORD TYPE NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING FI CODE DOMAIN
    IF L_CONTRACT.FI_CODE != '046' THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'FI CODE NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING CIB BRANCH CODE DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM BRANCHES WHERE CIB_BRANCH_CODE = L_CONTRACT.BRANCH_CODE;
    IF L_EXISTS = 0  THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'CIB BRANCH CODE NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING FI_SUBJECT_CODE DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM VW_SUBJECTS WHERE FI_SUBJECT_CODE = L_CONTRACT.FI_SUBJECT_CODE;
    IF L_EXISTS = 0  THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'FI SUBJECT CODE NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING SUBJECT ANOMALY
    SELECT SUM(CNT) INTO L_EXISTS FROM
    (SELECT COUNT(1) CNT FROM PERSONAL_DATA_ERROR WHERE VERSION_NO = L_VERSION_NO AND REPORTING_PERIOD = L_REPORTING_PERIOD AND FI_SUBJECT_CODE = L_CONTRACT.FI_SUBJECT_CODE
     UNION ALL
     SELECT COUNT(1) CNT FROM INSTITUTION_ERROR WHERE VERSION_NO = L_VERSION_NO AND REPORTING_PERIOD = L_REPORTING_PERIOD AND FI_SUBJECT_CODE = L_CONTRACT.FI_SUBJECT_CODE);
    IF L_EXISTS > 0 THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'FI SUBJECT CODE IN ANOMALY', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING CONTRACT TYPE DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM LOV_CONTRACT_TYPES WHERE CODE = L_CONTRACT.CONTRACT_TYPE;
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'CONTRACT TYPE NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING CONTRACT PHASE DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM LOV_CONTRACT_PHASES WHERE CODE = L_CONTRACT.CONTRACT_PHASE;
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'CONTRACT PHASE NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING CONTRACT STATUS DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM LOV_CONTRACT_STATUS WHERE CODE = L_CONTRACT.CONTRACT_STATUS;
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'CONTRACT STATUS NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING CURRENCY CODE BDT
    IF L_CONTRACT.CURRENCY_CODE != 'BDT' THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'CURRENCY CODE NOT BDT', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING DEFAULTER STATUS DOMAIN
    IF L_CONTRACT.DEFAULTER_STATUS != 'Y' AND L_CONTRACT.DEFAULTER_STATUS != 'N' AND L_CONTRACT.DEFAULTER_STATUS != 'W' THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'DEFAULTER STATUS NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING SUBSIDIZED CREDIT DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM LOV_SUBSIDIZED_CREDIT WHERE CODE = NVL(L_CONTRACT.SUBSIDIZED_CREDIT,'0');
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'SUBSIDIZED CREDIT NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING PRE FINANCE OF LOAN DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM LOV_PRE_FINANCE_OF_LOAN WHERE CODE = NVL(L_CONTRACT.PRE_FINANCE_LOAN, '0');
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'PRE FINANCE LOAN NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING CODE REORGANIZED CREDIT DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM LOV_REORGANIZED_CREDIT WHERE CODE = NVL(L_CONTRACT.REORGANIZED_CREDIT, '0');
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'CODE REORGANIZED CREDIT NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING THIRD PARTY GUARANTEE TYPE DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM LOV_3RD_PARTY_GUARANTEE_TYPES WHERE CODE = NVL(L_CONTRACT.THIRD_PARTY_GUARANTEE_TYPE,'72');
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'THIRD PARTY GUARANTEE TYPE NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING SECURITY TYPE DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM LOV_SECURITY_TYPES WHERE CODE = NVL(L_CONTRACT.SECURITY_TYPE,'10');
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'SECURITY TYPE NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING QUALITATIVE JUDGEMENT DOMAIN
    IF L_CONTRACT.QUALIFICATION_JUDGEMENT != 'Y' AND L_CONTRACT.QUALIFICATION_JUDGEMENT IS NOT NULL THEN
      L_IS_VALID := 0 ;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'QUALITATIVE JUDGEMENT NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CONTRACT PHASE = ["LV", "TM", "TA"] AND CONTRACT STARTING DATE IS EMPTY
    IF L_CONTRACT.CONTRACT_PHASE IN ('LV', 'TM', 'TA') AND L_CONTRACT.STARTING_DATE IS NULL THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'STARTING DATE EMPTY FOR "LV", "TM", "TA"', P_MAKE_BY, SYSDATE);
    END IF;

    -- CONTRACT PHASE = ["LV", "TM", "TA"] AND CONTRACT CATEGORY IS ["Instalments"] AND CONTRACT PLANNED END DATE IS EMPTY
    IF L_CONTRACT.CONTRACT_PHASE IN ('LV', 'TM', 'TA') AND L_CONTRACT.PLANNED_END_DATE IS NULL THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'PLANNED END DATE EMPTY FOR "LV", "TM", "TA"', P_MAKE_BY, SYSDATE);
    END IF;

    -- CONTRACT PHASE = ["TM", "TA"] AND CONTRACT ACTUAL END DATE IS EMPTY
    IF L_CONTRACT.CONTRACT_PHASE IN ('TM', 'TA') AND L_CONTRACT.ACTUAL_END_DATE IS NULL THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'ACTUAL END DATE EMPTY FOR "TM", "TA"', P_MAKE_BY, SYSDATE);
    END IF;

    -- LAST PAYMENT DATE IS NOT EMPTY AND FILE ACCOUNTING DATE < LAST PAYMENT DATE
    IF L_CONTRACT.LAST_PAYMENT_DATE IS NOT NULL AND L_REPORTING_PERIOD < L_CONTRACT.LAST_PAYMENT_DATE THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'LAST PAYMENT DATE GREATER THAN REPORTING PERIOD', P_MAKE_BY, SYSDATE);
    END IF;

    -- CONTRACT STARTING DATE > LAST PAYMENT DATE
    IF L_CONTRACT.LAST_PAYMENT_DATE IS NOT NULL AND L_CONTRACT.STARTING_DATE IS NOT NULL AND L_CONTRACT.STARTING_DATE > L_CONTRACT.LAST_PAYMENT_DATE THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'LAST PAYMENT DATE GREATER THAN STARTING DATE', P_MAKE_BY, SYSDATE);
    END IF;

    -- EXPIRATION DATE OF NEXT INSTALMENT IS NOT EMPTY AND CONTRACT STARTING DATE IS NOT EMPTY AND CONTRACT STARTING DATE > EXPIRATION DATE OF NEXT INSTALMENT
    IF L_CONTRACT.EXPIRATION_DATE_NEXT_INST IS NOT NULL AND L_CONTRACT.STARTING_DATE IS NOT NULL AND L_CONTRACT.STARTING_DATE > L_CONTRACT.EXPIRATION_DATE_NEXT_INST THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'THE CONTRACT CANNOT START AFTER A PAYMENT IS DUE', P_MAKE_BY, SYSDATE);
    END IF;

    -- EXPIRATION DATE OF NEXT INSTALMENT IS NOT EMPTY AND CONTRACT ACTUAL END DATE IS NOT EMPTY AND EXPIRATION DATE OF NEXT INSTALMENT > CONTRACT ACTUAL END DATE
    IF L_CONTRACT.EXPIRATION_DATE_NEXT_INST IS NOT NULL AND L_CONTRACT.ACTUAL_END_DATE IS NULL AND L_CONTRACT.EXPIRATION_DATE_NEXT_INST > L_CONTRACT.ACTUAL_END_DATE THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'EXPIRATION DATA GREATER THAN ACTUAL END DATE', P_MAKE_BY, SYSDATE);
    END IF;

    -- TOTAL FINANCED AMOUNT = [0] and CONTRACTCATEGORY = ["INSTALMENT"]
    IF L_CONTRACT.TOTAL_DISBURSED_AMOUNT IS NULL OR L_CONTRACT.TOTAL_DISBURSED_AMOUNT <= 0 THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'INVALID TOTAL DISBURSED AMOUNT', P_MAKE_BY, SYSDATE);
    END IF;

    -- TOTAL NUMBER OF INSTALMENT CANNOT BE ZERO
    IF L_CONTRACT.TOTAL_NUMBER_INSTALMENTS <= 0 THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'TOTAL NUMBER OF INSTALMENT INVALID', P_MAKE_BY, SYSDATE);
    END IF;

    -- PERIODICITY OF PAYMENT IS EMPTY AND CONTRACTCATEGORY = ["INSTALMENT"]
    SELECT COUNT(1) INTO L_EXISTS FROM LOV_PERIODICITY_OF_PAYMENT WHERE CODE = L_CONTRACT.PERIODICITY_PAYMENT;
    IF L_EXISTS = 0  THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'PERIODICITY OF PAYMENT NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- INSTALMENT AMOUNT = [0] and CONTRACTCATEGORY = ["instalment"] and CONTRACT PHASE = ["LV", "TM", "TA"]
    IF L_CONTRACT.CONTRACT_PHASE IN ('LV', 'TM', 'TA') AND L_CONTRACT.INSTALMENT_AMOUNT <= 0 THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'INSTALMENT AMOUNT INVALID FOR CONTRACT PHASE "LV","TM","TA"', P_MAKE_BY, SYSDATE);
    END IF;

    -- AMOUNT OF NEXT EXPIRING INSTALMENT > [0] AND CONTRACTCATEGORY = ["INSTALMENT"]) AND CONTRACT PHASE = ["TM", "TA"]
    IF L_CONTRACT.AMOUNT_NEXT_EXPIRING_INST IS NOT NULL AND L_CONTRACT.AMOUNT_NEXT_EXPIRING_INST > 0  AND L_CONTRACT.CONTRACT_PHASE IN ('TM', 'TA') THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'INVALID EXPIRING INSTALMENT FOR TM, TA', P_MAKE_BY, SYSDATE);
    END IF;

    -- NUMBER OF REMAINING INSTALMENTS = [0] AND CONTRACTCATEGORY = ["INSTALMENT"] AND CONTRACT PHASE = ["LV"]) AND FILE ACCOUNTING DATE < CONTRACT PLANNED END DATE
    IF L_CONTRACT.NO_OF_REMAINING_INSTALMENT IS NOT NULL AND L_CONTRACT.NO_OF_REMAINING_INSTALMENT = 0 AND L_CONTRACT.CONTRACT_PHASE = 'LV' AND L_CONTRACT.PLANNED_END_DATE IS NOT NULL AND L_REPORTING_PERIOD < L_CONTRACT.PLANNED_END_DATE THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, '0 INSTALMENT FOR LIVING CONTRACT', P_MAKE_BY, SYSDATE);
    END IF;

    -- NUMBER OF REMAINING INSTALMENTS > [0] AND CONTRACTCATEGORY = ["INSTALMENT"] AND CONTRACT PHASE = ["TM", "TA"]
    IF L_CONTRACT.NO_OF_REMAINING_INSTALMENT IS NOT NULL AND L_CONTRACT.NO_OF_REMAINING_INSTALMENT > 0 AND L_CONTRACT.CONTRACT_PHASE IN ('TM', 'TA') THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'INVALID NO OF REMAINING INSTALMENT FOR TM, TA', P_MAKE_BY, SYSDATE);
    END IF;

    -- REMAINING AMOUNT = [0] AND CONTRACTCATEGORY = ["INSTALMENT"]) AND CONTRACT PHASE = ["LV"] AND FILE ACCOUNTING DATE < CONTRACT PLANNED END DATE
    IF (L_CONTRACT.REMAINING_AMOUNT IS NULL OR L_CONTRACT.REMAINING_AMOUNT = 0) AND L_CONTRACT.CONTRACT_PHASE = 'LV' AND L_CONTRACT.PLANNED_END_DATE IS NOT NULL AND L_REPORTING_PERIOD < L_CONTRACT.PLANNED_END_DATE THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'REMAINING AMOUNT 0 FOR LV WITH FUTURE PLANNED END DATA', P_MAKE_BY, SYSDATE);
    END IF;

    -- REMAINING AMOUNT > [0] and CONTRACTCATEGORY = ["INSTALMENT"] and CONTRACT PHASE = ["TM", "TA"]
    IF L_CONTRACT.REMAINING_AMOUNT IS NOT NULL AND L_CONTRACT.REMAINING_AMOUNT > 0 AND L_CONTRACT.CONTRACT_PHASE IN ('TM','TA') THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'REMAINING AMOUNT NOT ZERO FOR TM, TA', P_MAKE_BY, SYSDATE);
    END IF;

    -- CONTRACTCATEGORY = ["instalment"] AND (((NUMBER OF REMAINING INSTALMENTS >[0]) AND (REMAINING AMOUNT = [0])) OR ((NUMBER OF REMAINING INSTALMENTS = [0]) AND (REMAINING AMOUNT > [0])))
    IF (L_CONTRACT.NO_OF_REMAINING_INSTALMENT IS NOT NULL AND L_CONTRACT.NO_OF_REMAINING_INSTALMENT > 0 AND L_CONTRACT.REMAINING_AMOUNT IS NOT NULL AND L_CONTRACT.REMAINING_AMOUNT = 0) OR
       (L_CONTRACT.NO_OF_REMAINING_INSTALMENT IS NOT NULL AND L_CONTRACT.NO_OF_REMAINING_INSTALMENT = 0 AND L_CONTRACT.REMAINING_AMOUNT IS NOT NULL AND L_CONTRACT.REMAINING_AMOUNT > 0) THEN
          L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'ANOMALY IN NO OF REMAINING INSTALMENT AND REMAINING AMOUNT', P_MAKE_BY, SYSDATE);
    END IF;

    -- NUMBER OF OVERDUE INSTALMENTS > [0] AND CONTRACT PHASE = ["RQ", "RN", "RF"]
    IF L_CONTRACT.NO_OF_OVERDUE_INSTALMENT IS NOT NULL AND L_CONTRACT.NO_OF_OVERDUE_INSTALMENT > 0 AND L_CONTRACT.CONTRACT_PHASE IN ('RQ', 'RN', 'RF') THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'NON ZERO NO OF OVERDUE INSTALMENT FOR RQ, RN, RF', P_MAKE_BY, SYSDATE);
    END IF;

    -- NUMBER OF OVERDUE AND NOT PAID INSTALMENTS > [0] AND CONTRACT PHASE = ["LV", "TM", "TA"] AND NUMBER OF OVERDUE AND NOT PAID INSTALMENTS > [TOTAL NUMBER OF INSTALMENTS - NUMBER OF REMAINING INSTALMENTS]
    IF L_CONTRACT.NO_OF_OVERDUE_INSTALMENT IS NOT NULL AND L_CONTRACT.NO_OF_OVERDUE_INSTALMENT > 0 AND L_CONTRACT.CONTRACT_PHASE IN ('LV', 'TM', 'TA') AND
       L_CONTRACT.NO_OF_REMAINING_INSTALMENT IS NOT NULL AND L_CONTRACT.NO_OF_OVERDUE_INSTALMENT > (L_CONTRACT.TOTAL_NUMBER_INSTALMENTS - L_CONTRACT.NO_OF_REMAINING_INSTALMENT) THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'ANOMALY IN NO OF OVERDUE INSTALMENT FOR LV, TM, TA', P_MAKE_BY, SYSDATE);
    END IF;

    -- OVERDUE AND NOT PAID AMOUNT > [0] AND CONTRACT PHASE = ["RQ", "RN", "RF"]
    IF L_CONTRACT.OVERDUE_AMOUNT IS NOT NULL AND L_CONTRACT.OVERDUE_AMOUNT > 0 AND L_CONTRACT.CONTRACT_PHASE IN ('RQ', 'RN', 'RF') THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'NON ZERO OVERDUE AMOUNT FOR RQ, RN, RF', P_MAKE_BY, SYSDATE);
    END IF;

    -- DATE OF LAW SUIT IS NOT EMPTY AND DATE OF LAW SUIT > FILE ACCOUNTING DATE
    IF L_CONTRACT.DATE_OF_LAW_SUIT IS NOT NULL AND L_REPORTING_PERIOD < L_CONTRACT.DATE_OF_LAW_SUIT THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'DATE OF LAW SUIT GREATER THAN REPORTING PERIOD', P_MAKE_BY, SYSDATE);
    END IF;

    -- DATE OF LAW SUIT IS NOT EMPTY AND DATE OF LAW SUIT < CONTRACT STARTING DATE
    IF L_CONTRACT.DATE_OF_LAW_SUIT IS NOT NULL AND L_CONTRACT.STARTING_DATE IS NOT NULL AND L_CONTRACT.DATE_OF_LAW_SUIT < L_CONTRACT.STARTING_DATE THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'DATE OF LAW SUIT GREATER THAN STARTING DATE', P_MAKE_BY, SYSDATE);
    END IF;

    -- DATE OF CLASSIFICATION IS NOT EMPTY AND DATE OF CLASSIFICATION > FILE ACCOUNTING DATE
    IF L_CONTRACT.DATE_OF_CLASSIFICATION IS NOT NULL AND L_CONTRACT.DATE_OF_CLASSIFICATION > L_REPORTING_PERIOD THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'DATE OF CLASSIFICATION GREATER THAN REPORTING PERIOD', P_MAKE_BY, SYSDATE);
    END IF;

    -- CONTRACT STATUS = ["S", "D", "B", "W"] AND DATE OF CLASSIFICATION IS EMPTY
    IF L_CONTRACT.DATE_OF_CLASSIFICATION IS NULL AND L_CONTRACT.CONTRACT_STATUS IN ('S', 'D', 'B', 'W') THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'DATE OF CLASSIFICATION NOT GIVEN FOR CLASSIFIED CONTRACT', P_MAKE_BY, SYSDATE);
    END IF;

    -- CLASSIFICATION DATE CANNOT BE PROVIDED FOR UNCLASSIFIED CONTRACT
    IF L_CONTRACT.DATE_OF_CLASSIFICATION IS NOT NULL AND L_CONTRACT.CONTRACT_STATUS IN('U','M') THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'DATE OF CLASSIFICATION NOT FOR UNCLASSIFIED CONTRACT', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECK IF PRIMARY SUBJECT IS IN ANOMALY
    SELECT SUM(A.CNT) INTO L_EXISTS FROM
    (SELECT COUNT(1) CNT FROM PERSONAL_DATA_ERROR WHERE VERSION_NO = L_VERSION_NO AND REPORTING_PERIOD = L_REPORTING_PERIOD AND FI_SUBJECT_CODE = L_CONTRACT.FI_SUBJECT_CODE
    UNION ALL
    SELECT COUNT(1) CNT FROM INSTITUTION_ERROR WHERE VERSION_NO = L_VERSION_NO AND REPORTING_PERIOD = L_REPORTING_PERIOD AND FI_SUBJECT_CODE = L_CONTRACT.FI_SUBJECT_CODE) A;
    IF L_EXISTS > 0 THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'PRIMARY SUBJECT IN ANOMALY', P_MAKE_BY, SYSDATE);
    END IF;

    IF L_CONTRACT.CONTRACT_STATUS = 'W' THEN
      L_IS_VALID := 1;
    END IF;

    IF L_IS_VALID = 1 THEN
      INSERT INTO INSTALMENT_CONTRACT_REPORT (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, P_MAKE_BY, SYSDATE);
      UPDATE INSTALMENT_CONTRACTS SET RECORD_STATUS = 'U' WHERE FI_CONTRACT_CODE = L_CONTRACT.FI_CONTRACT_CODE;
    ELSE
      UPDATE INSTALMENT_CONTRACTS SET RECORD_STATUS = 'E' WHERE FI_CONTRACT_CODE = L_CONTRACT.FI_CONTRACT_CODE;
    END IF;

  END LOOP;
END SP_VALIDATE_INST_CONTRACT;

-- ==================================
-- NON INSTALMENT CONTRACT VALIDATION
-- ==================================
PROCEDURE SP_VALIDATE_NON_INST_CONTRACT(P_MAKE_BY IN VARCHAR2)
AS
  TYPE T_REF_CURSOR IS REF CURSOR;

  L_CONTRACT NON_INSTALMENT_CONTRACTS%ROWTYPE;
  L_REF_CURSOR T_REF_CURSOR;
  L_IS_VALID INT;
  L_VERSION_NO NUMBER;
  L_REPORTING_PERIOD DATE;
  L_EXISTS INT;
BEGIN
  SELECT TO_DATE(VALUE,'DD-MON-YYYY') INTO L_REPORTING_PERIOD FROM REPORTING_PARAMETERS WHERE KEY = 'REPORTING_PERIOD';
  SELECT MAX(VERSION_NO)+1 INTO L_VERSION_NO FROM NON_INSTALMENT_CONTRACT_REPORT WHERE REPORTING_PERIOD = L_REPORTING_PERIOD;

  IF L_VERSION_NO IS NULL THEN L_VERSION_NO := 1; END IF;

  OPEN L_REF_CURSOR FOR SELECT * FROM NON_INSTALMENT_CONTRACTS WHERE RECORD_STATUS not in ('D', 'T') and STARTING_DATE <= L_REPORTING_PERIOD; --deleted or terminitated
  LOOP
    FETCH L_REF_CURSOR INTO L_CONTRACT;
    EXIT WHEN L_REF_CURSOR % NOTFOUND;

    L_IS_VALID := 1;

     -- CHECKING RECORD TYPE DOMAIN
    IF L_CONTRACT.RECORD_TYPE != 'D' THEN
      L_IS_VALID := 0;
      INSERT INTO NON_INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'RECORD TYPE NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING FI CODE DOMAIN
    IF L_CONTRACT.FI_CODE != '046' THEN
      L_IS_VALID := 0;
      INSERT INTO NON_INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'FI CODE NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING CIB BRANCH CODE DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM BRANCHES WHERE CIB_BRANCH_CODE = L_CONTRACT.BRANCH_CODE;
    IF L_EXISTS = 0  THEN
      L_IS_VALID := 0;
      INSERT INTO NON_INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'CIB BRANCH CODE NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING FI_SUBJECT_CODE DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM VW_SUBJECTS WHERE FI_SUBJECT_CODE = L_CONTRACT.FI_SUBJECT_CODE;
    IF L_EXISTS = 0  THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'FI SUBJECT CODE NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING SUBJECT ANOMALY
    SELECT SUM(CNT) INTO L_EXISTS FROM
    (SELECT COUNT(1) CNT FROM PERSONAL_DATA_ERROR WHERE VERSION_NO = L_VERSION_NO AND REPORTING_PERIOD = L_REPORTING_PERIOD AND FI_SUBJECT_CODE = L_CONTRACT.FI_SUBJECT_CODE
     UNION ALL
     SELECT COUNT(1) CNT FROM INSTITUTION_ERROR WHERE VERSION_NO = L_VERSION_NO AND REPORTING_PERIOD = L_REPORTING_PERIOD AND FI_SUBJECT_CODE = L_CONTRACT.FI_SUBJECT_CODE);
    IF L_EXISTS > 0 THEN
      L_IS_VALID := 0;
      INSERT INTO NON_INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'FI SUBJECT CODE IN ANOMALY', P_MAKE_BY, SYSDATE);
    END IF;


    -- CHECKING CONTRACT TYPE DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM LOV_CONTRACT_TYPES WHERE CODE = L_CONTRACT.CONTRACT_TYPE;
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO NON_INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'CONTRACT TYPE NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING CONTRACT PHASE DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM LOV_CONTRACT_PHASES WHERE CODE = L_CONTRACT.CONTRACT_PHASE;
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO NON_INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'CONTRACT PHASE NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING CONTRACT STATUS DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM LOV_CONTRACT_STATUS WHERE CODE = L_CONTRACT.CONTRACT_STATUS;
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO NON_INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'CONTRACT STATUS NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING CURRENCY CODE BDT
    IF L_CONTRACT.CURRENCY_CODE != 'BDT' THEN
      L_IS_VALID := 0;
      INSERT INTO NON_INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'CURRENCY CODE NOT BDT', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING DEFAULTER STATUS DOMAIN
    IF L_CONTRACT.DEFAULTER_STATUS != 'Y' AND L_CONTRACT.DEFAULTER_STATUS != 'N' AND L_CONTRACT.DEFAULTER_STATUS != 'W' THEN
      L_IS_VALID := 0;
      INSERT INTO NON_INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'DEFAULTER STATUS NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING SUBSIDIZED CREDIT DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM LOV_SUBSIDIZED_CREDIT WHERE CODE = NVL(L_CONTRACT.SUBSIDIZED_CREDIT,'0');
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO NON_INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'SUBSIDIZED CREDIT NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING PRE FINANCE OF LOAN DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM LOV_PRE_FINANCE_OF_LOAN WHERE CODE = NVL(L_CONTRACT.PRE_FINANCE_LOAN, '0');
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO NON_INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'PRE FINANCE LOAN NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING CODE REORGANIZED CREDIT DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM LOV_REORGANIZED_CREDIT WHERE CODE = NVL(L_CONTRACT.REORGANIZED_CREDIT, '0');
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO NON_INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'CODE REORGANIZED CREDIT NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING THIRD PARTY GUARANTEE TYPE DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM LOV_3RD_PARTY_GUARANTEE_TYPES WHERE CODE = NVL(L_CONTRACT.THIRD_PARTY_GUARANTEE_TYPE,'72');
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO NON_INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'THIRD PARTY GUARANTEE TYPE NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING SECURITY TYPE DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM LOV_SECURITY_TYPES WHERE CODE = NVL(L_CONTRACT.SECURITY_TYPE,'10');
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO NON_INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'SECURITY TYPE NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING QUALITATIVE JUDGEMENT DOMAIN
    IF L_CONTRACT.QUALITATIVE_JUDGEMENT != 'Y' AND L_CONTRACT.QUALITATIVE_JUDGEMENT IS NOT NULL THEN
      L_IS_VALID := 0 ;
      INSERT INTO NON_INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'QUALITATIVE JUDGEMENT NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CONTRACT PHASE = ["LV", "TM", "TA"] AND CONTRACT STARTING DATE IS EMPTY
    IF L_CONTRACT.CONTRACT_PHASE IN ('LV', 'TM', 'TA') AND L_CONTRACT.STARTING_DATE IS NULL THEN
      L_IS_VALID := 0;
      INSERT INTO NON_INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'STARTING DATE EMPTY FOR "LV", "TM", "TA"', P_MAKE_BY, SYSDATE);
    END IF;

    -- CONTRACT PHASE = ["LV", "TM", "TA"] AND CONTRACT CATEGORY IS ["Instalments"] AND CONTRACT PLANNED END DATE IS EMPTY
    IF L_CONTRACT.CONTRACT_PHASE IN ('LV', 'TM', 'TA') AND L_CONTRACT.PLANNED_END_DATE IS NULL THEN
      L_IS_VALID := 0;
      INSERT INTO NON_INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'PLANNED END DATE EMPTY FOR "LV", "TM", "TA"', P_MAKE_BY, SYSDATE);
    END IF;

    -- CONTRACT PHASE = ["TM", "TA"] AND CONTRACT ACTUAL END DATE IS EMPTY
    IF L_CONTRACT.CONTRACT_PHASE IN ('TM', 'TA') AND L_CONTRACT.ACTUAL_END_DATE IS NULL THEN
      L_IS_VALID := 0;
      INSERT INTO NON_INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'ACTUAL END DATE EMPTY FOR "TM", "TA"', P_MAKE_BY, SYSDATE);
    END IF;

    -- LAST PAYMENT DATE IS NOT EMPTY AND FILE ACCOUNTING DATE < LAST PAYMENT DATE
    IF L_CONTRACT.DATE_OF_LAST_PAYMENT IS NOT NULL AND L_REPORTING_PERIOD < L_CONTRACT.DATE_OF_LAST_PAYMENT THEN
      L_IS_VALID := 0;
      INSERT INTO NON_INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'LAST PAYMENT DATE GREATER THAN REPORTING PERIOD', P_MAKE_BY, SYSDATE);
    END IF;

    -- CONTRACT STARTING DATE > LAST PAYMENT DATE
    IF L_CONTRACT.DATE_OF_LAST_PAYMENT IS NOT NULL AND L_CONTRACT.STARTING_DATE IS NOT NULL AND L_CONTRACT.STARTING_DATE > L_CONTRACT.DATE_OF_LAST_PAYMENT THEN
      L_IS_VALID := 0;
      INSERT INTO NON_INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'LAST PAYMENT DATE GREATER THAN STARTING DATE', P_MAKE_BY, SYSDATE);
    END IF;

    -- DATE OF LAW SUIT IS NOT EMPTY AND DATE OF LAW SUIT > FILE ACCOUNTING DATE
    IF L_CONTRACT.DATE_OF_LAW_SUIT IS NOT NULL AND L_REPORTING_PERIOD < L_CONTRACT.DATE_OF_LAW_SUIT THEN
      L_IS_VALID := 0;
      INSERT INTO NON_INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'DATE OF LAW SUIT GREATER THAN REPORTING PERIOD', P_MAKE_BY, SYSDATE);
    END IF;

    -- DATE OF LAW SUIT IS NOT EMPTY AND DATE OF LAW SUIT < CONTRACT STARTING DATE
    IF L_CONTRACT.DATE_OF_LAW_SUIT IS NOT NULL AND L_CONTRACT.STARTING_DATE IS NOT NULL AND L_CONTRACT.DATE_OF_LAW_SUIT < L_CONTRACT.STARTING_DATE THEN
      L_IS_VALID := 0;
      INSERT INTO NON_INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'DATE OF LAW SUIT GREATER THAN STARTING DATE', P_MAKE_BY, SYSDATE);
    END IF;

    -- DATE OF CLASSIFICATION IS NOT EMPTY AND DATE OF CLASSIFICATION > FILE ACCOUNTING DATE
    IF L_CONTRACT.DATE_OF_CLASSIFICATION IS NOT NULL AND L_CONTRACT.DATE_OF_CLASSIFICATION > L_REPORTING_PERIOD THEN
      L_IS_VALID := 0;
      INSERT INTO NON_INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'DATE OF CLASSIFICATION GREATER THAN REPORTING PERIOD', P_MAKE_BY, SYSDATE);
    END IF;

    -- CONTRACT STATUS = ["S", "D", "B", "W"] AND DATE OF CLASSIFICATION IS EMPTY
    IF L_CONTRACT.DATE_OF_CLASSIFICATION IS NULL AND L_CONTRACT.CONTRACT_STATUS IN ('S', 'D', 'B', 'W') THEN
      L_IS_VALID := 0;
      INSERT INTO NON_INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'DATE OF CLASSIFICATION NOT GIVEN FOR CLASSIFIED CONTRACT', P_MAKE_BY, SYSDATE);
    END IF;

    -- CLASSIFICATION DATE CANNOT BE PROVIDED FOR UNCLASSIFIED CONTRACT
    IF L_CONTRACT.DATE_OF_CLASSIFICATION IS NOT NULL AND L_CONTRACT.CONTRACT_STATUS IN('U','M') THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'DATE OF CLASSIFICATION NOT FOR UNCLASSIFIED CONTRACT', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECK IF PRIMARY SUBJECT IS IN ANOMALY
    SELECT SUM(A.CNT) INTO L_EXISTS FROM
    (SELECT COUNT(1) CNT FROM PERSONAL_DATA_ERROR WHERE VERSION_NO = L_VERSION_NO AND REPORTING_PERIOD = L_REPORTING_PERIOD AND FI_SUBJECT_CODE = L_CONTRACT.FI_SUBJECT_CODE
    UNION ALL
    SELECT COUNT(1) CNT FROM INSTITUTION_ERROR WHERE VERSION_NO = L_VERSION_NO AND REPORTING_PERIOD = L_REPORTING_PERIOD AND FI_SUBJECT_CODE = L_CONTRACT.FI_SUBJECT_CODE) A;
    IF L_EXISTS > 0 THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'PRIMARY SUBJECT IN ANOMALY', P_MAKE_BY, SYSDATE);
    END IF;

    IF L_CONTRACT.CONTRACT_STATUS = 'W' THEN
      L_IS_VALID := 1;
    END IF;

    IF L_IS_VALID = 1 THEN
      INSERT INTO NON_INSTALMENT_CONTRACT_REPORT (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, P_MAKE_BY, SYSDATE);
      UPDATE NON_INSTALMENT_CONTRACTS SET RECORD_STATUS = 'U' WHERE FI_CONTRACT_CODE = L_CONTRACT.FI_CONTRACT_CODE;
    ELSE
      UPDATE NON_INSTALMENT_CONTRACTS SET RECORD_STATUS = 'E' WHERE FI_CONTRACT_CODE = L_CONTRACT.FI_CONTRACT_CODE;
    END IF;
  END LOOP;
END SP_VALIDATE_NON_INST_CONTRACT;

-- ========================
-- CARD CONTRACT VALIDATION
-- ========================
PROCEDURE SP_VALIDATE_CARD_CONTRACT(P_MAKE_BY IN VARCHAR2)
AS
  TYPE T_REF_CURSOR IS REF CURSOR;

  L_CONTRACT CARD_CONTRACTS%ROWTYPE;
  L_REF_CURSOR T_REF_CURSOR;
  L_IS_VALID INT;
  L_VERSION_NO NUMBER;
  L_REPORTING_PERIOD DATE;
  L_EXISTS INT;
BEGIN
  SELECT TO_DATE(VALUE,'DD-MON-YYYY') INTO L_REPORTING_PERIOD FROM REPORTING_PARAMETERS WHERE KEY = 'REPORTING_PERIOD';
  SELECT MAX(VERSION_NO)+1 INTO L_VERSION_NO FROM CARD_CONTRACT_REPORT WHERE REPORTING_PERIOD = L_REPORTING_PERIOD;

  IF L_VERSION_NO IS NULL THEN L_VERSION_NO := 1; END IF;

  OPEN L_REF_CURSOR FOR SELECT * FROM CARD_CONTRACTS WHERE RECORD_STATUS not in ('D', 'T') and STARTING_DATE <= L_REPORTING_PERIOD; --deleted or terminitated
  LOOP
    FETCH L_REF_CURSOR INTO L_CONTRACT;
    EXIT WHEN L_REF_CURSOR % NOTFOUND;

    L_IS_VALID := 1;

    -- CHECKING RECORD TYPE DOMAIN
    IF L_CONTRACT.RECORD_TYPE != 'D' THEN
      L_IS_VALID := 0;
      INSERT INTO CARD_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'RECORD TYPE NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING FI CODE DOMAIN
    IF L_CONTRACT.FI_CODE != '046' THEN
      L_IS_VALID := 0;
      INSERT INTO CARD_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'FI CODE NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING CIB BRANCH CODE DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM BRANCHES WHERE CIB_BRANCH_CODE = L_CONTRACT.BRANCH_CODE;
    IF L_EXISTS = 0  THEN
      L_IS_VALID := 0;
      INSERT INTO CARD_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'CIB BRANCH CODE NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING FI_SUBJECT_CODE DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM VW_SUBJECTS WHERE FI_SUBJECT_CODE = L_CONTRACT.FI_SUBJECT_CODE;
    IF L_EXISTS = 0  THEN
      L_IS_VALID := 0;
      INSERT INTO CARD_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'FI SUBJECT CODE NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING SUBJECT ANOMALY
    SELECT COUNT(1) INTO L_EXISTS FROM PERSONAL_DATA_ERROR WHERE VERSION_NO = L_VERSION_NO AND REPORTING_PERIOD = L_REPORTING_PERIOD AND FI_SUBJECT_CODE = L_CONTRACT.FI_SUBJECT_CODE;
    IF L_EXISTS > 0 THEN
      L_IS_VALID := 0;
      INSERT INTO CARD_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'FI SUBJECT CODE IN ANOMALY', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING CONTRACT TYPE DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM LOV_CONTRACT_TYPES WHERE CODE = L_CONTRACT.CONTRACT_TYPE;
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO CARD_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'CONTRACT TYPE NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING CONTRACT PHASE DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM LOV_CONTRACT_PHASES WHERE CODE = L_CONTRACT.CONTRACT_PHASE;
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO CARD_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'CONTRACT PHASE NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING CONTRACT STATUS DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM LOV_CONTRACT_STATUS WHERE CODE = L_CONTRACT.CONTRACT_STATUS;
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO CARD_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'CONTRACT STATUS NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING CURRENCY CODE BDT
    IF L_CONTRACT.CURRENCY_CODE != 'BDT' THEN
      L_IS_VALID := 0;
      INSERT INTO CARD_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'CURRENCY CODE NOT BDT', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING DEFAULTER STATUS DOMAIN
    IF L_CONTRACT.DEFAULTER_STATUS != 'Y' AND L_CONTRACT.DEFAULTER_STATUS != 'N' AND L_CONTRACT.DEFAULTER_STATUS != 'W' THEN
      L_IS_VALID := 0;
      INSERT INTO CARD_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'DEFAULTER STATUS NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING SUBSIDIZED CREDIT DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM LOV_SUBSIDIZED_CREDIT WHERE CODE = NVL(L_CONTRACT.SUBSIDIZED_CREDIT,'0');
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO CARD_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'SUBSIDIZED CREDIT NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING PRE FINANCE OF LOAN DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM LOV_PRE_FINANCE_OF_LOAN WHERE CODE = NVL(L_CONTRACT.PRE_FINANCE_OF_LOAN, '0');
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO CARD_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'PRE FINANCE LOAN NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING CODE REORGANIZED CREDIT DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM LOV_REORGANIZED_CREDIT WHERE CODE = NVL(L_CONTRACT.REORGANIZED_CREDIT, '0');
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO CARD_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'CODE REORGANIZED CREDIT NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING THIRD PARTY GUARANTEE TYPE DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM LOV_3RD_PARTY_GUARANTEE_TYPES WHERE CODE = NVL(L_CONTRACT.THIRD_PARTY_GUARANTEE_TYPE,'72');
