    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO CARD_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'SECURITY TYPE NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECKING QUALITATIVE JUDGEMENT DOMAIN
    IF L_CONTRACT.QUALITATIVE_JUDGEMENT != 'Y' AND L_CONTRACT.QUALITATIVE_JUDGEMENT IS NOT NULL THEN
      L_IS_VALID := 0 ;
      INSERT INTO CARD_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'QUALITATIVE JUDGEMENT NOT IN DOMAIN', P_MAKE_BY, SYSDATE);
    END IF;

    -- CONTRACT PHASE = ["LV", "TM", "TA"] AND CONTRACT STARTING DATE IS EMPTY
    IF L_CONTRACT.CONTRACT_PHASE IN ('LV', 'TM', 'TA') AND L_CONTRACT.STARTING_DATE IS NULL THEN
      L_IS_VALID := 0;
      INSERT INTO CARD_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'STARTING DATE EMPTY FOR "LV", "TM", "TA"', P_MAKE_BY, SYSDATE);
    END IF;


    -- CONTRACT PHASE = ["TM", "TA"] AND CONTRACT ACTUAL END DATE IS EMPTY
    IF L_CONTRACT.CONTRACT_PHASE IN ('TM', 'TA') AND L_CONTRACT.ACTUAL_END_DATE IS NULL THEN
      L_IS_VALID := 0;
      INSERT INTO CARD_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'ACTUAL END DATE EMPTY FOR "TM", "TA"', P_MAKE_BY, SYSDATE);
    END IF;

    -- LAST PAYMENT DATE IS NOT EMPTY AND FILE ACCOUNTING DATE < LAST PAYMENT DATE
    IF L_CONTRACT.DATE_LAST_PAYMENT IS NOT NULL AND L_REPORTING_PERIOD < L_CONTRACT.DATE_LAST_PAYMENT THEN
      L_IS_VALID := 0;
      INSERT INTO CARD_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'LAST PAYMENT DATE GREATER THAN REPORTING PERIOD', P_MAKE_BY, SYSDATE);
    END IF;

    -- CONTRACT STARTING DATE > LAST PAYMENT DATE
    IF L_CONTRACT.DATE_LAST_PAYMENT IS NOT NULL AND L_CONTRACT.STARTING_DATE IS NOT NULL AND L_CONTRACT.STARTING_DATE > L_CONTRACT.DATE_LAST_PAYMENT THEN
      L_IS_VALID := 0;
      INSERT INTO CARD_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'LAST PAYMENT DATE GREATER THAN STARTING DATE', P_MAKE_BY, SYSDATE);
    END IF;

    -- EXPIRATION DATE OF NEXT INSTALMENT IS NOT EMPTY AND CONTRACT STARTING DATE IS NOT EMPTY AND CONTRACT STARTING DATE > EXPIRATION DATE OF NEXT INSTALMENT
    IF L_CONTRACT.EXPIRATION_DATE_NEXT_INST IS NOT NULL AND L_CONTRACT.STARTING_DATE IS NOT NULL AND L_CONTRACT.STARTING_DATE > L_CONTRACT.EXPIRATION_DATE_NEXT_INST THEN
      L_IS_VALID := 0;
      INSERT INTO CARD_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'THE CONTRACT CANNOT START AFTER A PAYMENT IS DUE', P_MAKE_BY, SYSDATE);
    END IF;

    -- EXPIRATION DATE OF NEXT INSTALMENT IS NOT EMPTY AND CONTRACT ACTUAL END DATE IS NOT EMPTY AND EXPIRATION DATE OF NEXT INSTALMENT > CONTRACT ACTUAL END DATE
    IF L_CONTRACT.EXPIRATION_DATE_NEXT_INST IS NOT NULL AND L_CONTRACT.ACTUAL_END_DATE IS NULL AND L_CONTRACT.EXPIRATION_DATE_NEXT_INST > L_CONTRACT.ACTUAL_END_DATE THEN
      L_IS_VALID := 0;
      INSERT INTO CARD_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'EXPIRATION DATA GREATER THAN ACTUAL END DATE', P_MAKE_BY, SYSDATE);
    END IF;

    -- NUMBER OF OVERDUE INSTALMENTS > [0] AND CONTRACT PHASE = ["RQ", "RN", "RF"]
    IF L_CONTRACT.NUMBER_OF_OVERDUE IS NOT NULL AND L_CONTRACT.NUMBER_OF_OVERDUE > 0 AND L_CONTRACT.CONTRACT_PHASE IN ('RQ', 'RN', 'RF') THEN
      L_IS_VALID := 0;
      INSERT INTO CARD_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'NON ZERO NO OF OVERDUE INSTALMENT FOR RQ, RN, RF', P_MAKE_BY, SYSDATE);
    END IF;

    -- OVERDUE AND NOT PAID AMOUNT > [0] AND CONTRACT PHASE = ["RQ", "RN", "RF"]
    IF L_CONTRACT.OVERDUE_AMOUNT IS NOT NULL AND L_CONTRACT.OVERDUE_AMOUNT > 0 AND L_CONTRACT.CONTRACT_PHASE IN ('RQ', 'RN', 'RF') THEN
      L_IS_VALID := 0;
      INSERT INTO CARD_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'NON ZERO OVERDUE AMOUNT FOR RQ, RN, RF', P_MAKE_BY, SYSDATE);
    END IF;

    -- DATE OF LAW SUIT IS NOT EMPTY AND DATE OF LAW SUIT > FILE ACCOUNTING DATE
    IF L_CONTRACT.DATE_OF_LAW_SUIT IS NOT NULL AND L_REPORTING_PERIOD < L_CONTRACT.DATE_OF_LAW_SUIT THEN
      L_IS_VALID := 0;
      INSERT INTO CARD_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'DATE OF LAW SUIT GREATER THAN REPORTING PERIOD', P_MAKE_BY, SYSDATE);
    END IF;

    -- DATE OF LAW SUIT IS NOT EMPTY AND DATE OF LAW SUIT < CONTRACT STARTING DATE
    IF L_CONTRACT.DATE_OF_LAW_SUIT IS NOT NULL AND L_CONTRACT.STARTING_DATE IS NOT NULL AND L_CONTRACT.DATE_OF_LAW_SUIT < L_CONTRACT.STARTING_DATE THEN
      L_IS_VALID := 0;
      INSERT INTO CARD_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'DATE OF LAW SUIT GREATER THAN STARTING DATE', P_MAKE_BY, SYSDATE);
    END IF;

    -- DATE OF CLASSIFICATION IS NOT EMPTY AND DATE OF CLASSIFICATION > FILE ACCOUNTING DATE
    IF L_CONTRACT.DATE_OF_CLASSIFICATION IS NOT NULL AND L_CONTRACT.DATE_OF_CLASSIFICATION > L_REPORTING_PERIOD THEN
      L_IS_VALID := 0;
      INSERT INTO CARD_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'DATE OF CLASSIFICATION GREATER THAN REPORTING PERIOD', P_MAKE_BY, SYSDATE);
    END IF;

    -- CONTRACT STATUS = ["S", "D", "B", "W"] AND DATE OF CLASSIFICATION IS EMPTY
    IF L_CONTRACT.DATE_OF_CLASSIFICATION IS NULL AND L_CONTRACT.CONTRACT_STATUS IN ('S', 'D', 'B', 'W') THEN
      L_IS_VALID := 0;
      INSERT INTO CARD_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'DATE OF CLASSIFICATION NOT GIVEN FOR CLASSIFIED CONTRACT', P_MAKE_BY, SYSDATE);
    END IF;

    -- CLASSIFICATION DATE CANNOT BE PROVIDED FOR UNCLASSIFIED CONTRACT
    IF L_CONTRACT.DATE_OF_CLASSIFICATION IS NOT NULL AND L_CONTRACT.CONTRACT_STATUS IN('U','M') THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'DATE OF CLASSIFICATION NOT FOR UNCLASSIFIED CONTRACT', P_MAKE_BY, SYSDATE);
    END IF;

    -- CREDIT limit = [0] and CONTRACTCATEGORY = ["CARD"]
    IF L_CONTRACT.CREDIT_LIMIT = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO CARD_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'CREDIT LIMIT CANNOT BE ZERO', P_MAKE_BY, SYSDATE);
    END IF;

    -- PERIODICITY OF PAYMENT IS EMPTY AND CONTRACTCATEGORY = ["CARD"] AND CONTRACT TYPE <> ["RV"]
    SELECT COUNT(1) INTO L_EXISTS FROM LOV_PERIODICITY_OF_PAYMENT WHERE CODE = NVL(L_CONTRACT.PERIODICITY_PAYMENT, '~');
    IF L_EXISTS = 0 AND L_CONTRACT.CONTRACT_TYPE = 'RV' THEN
      L_IS_VALID := 0;
      INSERT INTO CARD_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'PERIODICITY PAYMENT NOT GIVEN FOR RV', P_MAKE_BY, SYSDATE);
    END IF;

    -- CHECK IF PRIMARY SUBJECT IS IN ANOMALY
    SELECT SUM(A.CNT) INTO L_EXISTS FROM
    (SELECT COUNT(1) CNT FROM PERSONAL_DATA_ERROR WHERE VERSION_NO = L_VERSION_NO AND REPORTING_PERIOD = L_REPORTING_PERIOD AND FI_SUBJECT_CODE = L_CONTRACT.FI_SUBJECT_CODE
    UNION ALL
    SELECT COUNT(1) CNT FROM INSTITUTION_ERROR WHERE VERSION_NO = L_VERSION_NO AND REPORTING_PERIOD = L_REPORTING_PERIOD AND FI_SUBJECT_CODE = L_CONTRACT.FI_SUBJECT_CODE) A;
    IF L_EXISTS > 0 THEN
      L_IS_VALID := 0;
      INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, NULL, 'PRIMARY SUBJECT IN ANOMALY', P_MAKE_BY, SYSDATE);
    END IF;

    IF L_IS_VALID = 1 THEN
      INSERT INTO CARD_CONTRACT_REPORT (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_CONTRACT.FI_CONTRACT_CODE, P_MAKE_BY, SYSDATE);
      UPDATE CARD_CONTRACTS SET RECORD_STATUS = 'U' WHERE FI_CONTRACT_CODE = L_CONTRACT.FI_CONTRACT_CODE;
    ELSE
      UPDATE CARD_CONTRACTS SET RECORD_STATUS = 'E' WHERE FI_CONTRACT_CODE = L_CONTRACT.FI_CONTRACT_CODE;
    END IF;

  END LOOP;
END SP_VALIDATE_CARD_CONTRACT;

-- ========================
-- CONTRACT LINK VALIDATION
-- ========================
PROCEDURE SP_VALIDATE_CONTRACT_LINK(P_MAKE_BY IN VARCHAR2)
AS
  TYPE T_REF_CURSOR IS REF CURSOR;

  L_LINK CONTRACT_LINKS%ROWTYPE;
  L_REF_CURSOR T_REF_CURSOR;
  L_IS_VALID INT;
  L_VERSION_NO NUMBER;
  L_REPORTING_PERIOD DATE;
  L_EXISTS INT;
BEGIN
  SELECT TO_DATE(VALUE,'DD-MON-YYYY') INTO L_REPORTING_PERIOD FROM REPORTING_PARAMETERS WHERE KEY = 'REPORTING_PERIOD';
  SELECT MAX(VERSION_NO)+1 INTO L_VERSION_NO FROM CONTRACT_LINK_REPORT WHERE REPORTING_PERIOD = L_REPORTING_PERIOD;

  IF L_VERSION_NO IS NULL THEN L_VERSION_NO := 1; END IF;

  OPEN L_REF_CURSOR FOR SELECT * FROM CONTRACT_LINKS WHERE RECORD_STATUS NOT IN ('D','R');
  LOOP
    FETCH L_REF_CURSOR INTO L_LINK;
    EXIT WHEN L_REF_CURSOR % NOTFOUND;

    L_IS_VALID := 1;

    -- CHECKING RECORD TYPE DOMAIN
    IF L_LINK.RECORD_TYPE != 'G' THEN
      L_IS_VALID := 0;
      INSERT INTO CONTRACT_LINK_ERROR (VERSION_NO, REPORTING_PERIOD, FI_PRIMARY_CODE, FI_SECONDARY_CODE, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_LINK.FI_PRIMARY_CODE, L_LINK.FI_SECONDARY_CODE, L_LINK.FI_CONTRACT_CODE, NULL, 'RECORD TYPE NOT IN DOMAIN', P_MAKE_BY, SYSDATE );
    END IF;

    -- CHECKING FI CODE
    IF L_LINK.FI_CODE != '046' THEN
      L_IS_VALID := 0;
      INSERT INTO CONTRACT_LINK_ERROR (VERSION_NO, REPORTING_PERIOD, FI_PRIMARY_CODE, FI_SECONDARY_CODE, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_LINK.FI_PRIMARY_CODE, L_LINK.FI_SECONDARY_CODE, L_LINK.FI_CONTRACT_CODE, NULL, 'FI CODE NOT CORRECT', P_MAKE_BY, SYSDATE );
    END IF;

    -- CHECKING CIB BRANCH CODE DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM BRANCHES WHERE CIB_BRANCH_CODE = L_LINK.BRANCH_CODE;
    IF L_EXISTS = 0  THEN
      L_IS_VALID := 0;
      INSERT INTO CONTRACT_LINK_ERROR (VERSION_NO, REPORTING_PERIOD, FI_PRIMARY_CODE, FI_SECONDARY_CODE, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_LINK.FI_PRIMARY_CODE, L_LINK.FI_SECONDARY_CODE, L_LINK.FI_CONTRACT_CODE, NULL, 'BRANCH CODE NOT IN DOMAIN', P_MAKE_BY, SYSDATE );
    END IF;

    -- CHECKING PRIMARY SUBJECT DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM VW_SUBJECTS WHERE FI_SUBJECT_CODE = L_LINK.FI_PRIMARY_CODE;
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO CONTRACT_LINK_ERROR (VERSION_NO, REPORTING_PERIOD, FI_PRIMARY_CODE, FI_SECONDARY_CODE, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_LINK.FI_PRIMARY_CODE, L_LINK.FI_SECONDARY_CODE, L_LINK.FI_CONTRACT_CODE, NULL, 'PRIMARY SUBJECT NOT IN DOMAIN', P_MAKE_BY, SYSDATE );
    END IF;

    -- CHECKING SECONDARY SUBJECT DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM VW_SUBJECTS WHERE FI_SUBJECT_CODE = L_LINK.FI_SECONDARY_CODE;
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO CONTRACT_LINK_ERROR (VERSION_NO, REPORTING_PERIOD, FI_PRIMARY_CODE, FI_SECONDARY_CODE, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_LINK.FI_PRIMARY_CODE, L_LINK.FI_SECONDARY_CODE, L_LINK.FI_CONTRACT_CODE, NULL, 'SECONDARY SUBJECT NOT IN DOMAIN', P_MAKE_BY, SYSDATE );
    END IF;

    -- CHECKING CONTRACT DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM VW_CONTRACTS WHERE FI_CONTRACT_CODE = L_LINK.FI_CONTRACT_CODE;
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO CONTRACT_LINK_ERROR (VERSION_NO, REPORTING_PERIOD, FI_PRIMARY_CODE, FI_SECONDARY_CODE, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_LINK.FI_PRIMARY_CODE, L_LINK.FI_SECONDARY_CODE, L_LINK.FI_CONTRACT_CODE, NULL, 'CONTRACT NOT IN DOMAIN', P_MAKE_BY, SYSDATE );
    END IF;

    -- CHECKING TYPE OF LINK DOMAIN
    SELECT COUNT(1) INTO L_EXISTS FROM LOV_LINK_TYPES WHERE CODE = L_LINK.TYPE_OF_LINK;
    IF L_EXISTS = 0 THEN
      L_IS_VALID := 0;
      INSERT INTO CONTRACT_LINK_ERROR (VERSION_NO, REPORTING_PERIOD, FI_PRIMARY_CODE, FI_SECONDARY_CODE, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_LINK.FI_PRIMARY_CODE, L_LINK.FI_SECONDARY_CODE, L_LINK.FI_CONTRACT_CODE, NULL, 'TYPE OF LINK NOT IN DOMAIN', P_MAKE_BY, SYSDATE );
      -- FLAG LINK AS ERROR
      UPDATE CONTRACT_LINKS
      SET RECORD_STATUS = 'E'
      WHERE FI_PRIMARY_CODE = L_LINK.FI_PRIMARY_CODE
      AND FI_SECONDARY_CODE = L_LINK.FI_SECONDARY_CODE
      AND FI_CONTRACT_CODE = L_LINK.FI_CONTRACT_CODE;
    END IF;

    -- CHECKING PRIMARY AND SECONDARY CODE SAME
    IF L_LINK.FI_PRIMARY_CODE = L_LINK.FI_SECONDARY_CODE THEN
      L_IS_VALID := 0;
      INSERT INTO CONTRACT_LINK_ERROR (VERSION_NO, REPORTING_PERIOD, FI_PRIMARY_CODE, FI_SECONDARY_CODE, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_LINK.FI_PRIMARY_CODE, L_LINK.FI_SECONDARY_CODE, L_LINK.FI_CONTRACT_CODE, NULL, 'LINKED SUBJECT AND APPLICANT ARE THE SAME SUBJECT', P_MAKE_BY, SYSDATE );
      -- FLAG LINK AS ERROR
      UPDATE CONTRACT_LINKS
      SET RECORD_STATUS = 'E'
      WHERE FI_PRIMARY_CODE = L_LINK.FI_PRIMARY_CODE
      AND FI_SECONDARY_CODE = L_LINK.FI_SECONDARY_CODE
      AND FI_CONTRACT_CODE = L_LINK.FI_CONTRACT_CODE;
    END IF;

    -- CHECKING PRIMARY SUBJECT FOR ANOMALY
    SELECT SUM(A.CNT) INTO L_EXISTS FROM
    (SELECT COUNT(1) CNT FROM PERSONAL_DATA_ERROR WHERE VERSION_NO = L_VERSION_NO AND REPORTING_PERIOD = L_REPORTING_PERIOD AND FI_SUBJECT_CODE = L_LINK.FI_PRIMARY_CODE
    UNION ALL
    SELECT COUNT(1) CNT FROM INSTITUTION_ERROR WHERE VERSION_NO = L_VERSION_NO AND REPORTING_PERIOD = L_REPORTING_PERIOD AND FI_SUBJECT_CODE = L_LINK.FI_PRIMARY_CODE) A;
    IF L_EXISTS > 0 THEN
      L_IS_VALID := 0;
      INSERT INTO CONTRACT_LINK_ERROR (VERSION_NO, REPORTING_PERIOD, FI_PRIMARY_CODE, FI_SECONDARY_CODE, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
      VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_LINK.FI_PRIMARY_CODE, L_LINK.FI_SECONDARY_CODE, L_LINK.FI_CONTRACT_CODE, NULL, 'PRIMARY SUBJECT "'||L_LINK.FI_PRIMARY_CODE||'" IN ANOMALY', P_MAKE_BY, SYSDATE );

      -- MOVING SECONDARY SUBJECT TO ERROR
      -- FIRST CHECK IF SUBJECT HAS OTHER CONTRACTS OR COMPANY LINKS
      SELECT SUM(AA.CNT) INTO L_EXISTS FROM
      (
      SELECT COUNT(1) CNT FROM INSTALMENT_CONTRACT_REPORT A JOIN INSTALMENT_CONTRACTS B ON A.FI_CONTRACT_CODE = B.FI_CONTRACT_CODE WHERE VERSION_NO = L_VERSION_NO AND REPORTING_PERIOD = L_REPORTING_PERIOD AND B.FI_SUBJECT_CODE = L_LINK.FI_SECONDARY_CODE
      UNION ALL
      SELECT COUNT(1) CNT FROM NON_INSTALMENT_CONTRACT_REPORT A JOIN NON_INSTALMENT_CONTRACTS B ON A.FI_CONTRACT_CODE = B.FI_CONTRACT_CODE WHERE VERSION_NO = L_VERSION_NO AND REPORTING_PERIOD = L_REPORTING_PERIOD AND B.FI_SUBJECT_CODE = L_LINK.FI_SECONDARY_CODE
      UNION ALL
      SELECT COUNT(1) CNT FROM CARD_CONTRACT_REPORT A JOIN CARD_CONTRACTS B ON A.FI_CONTRACT_CODE = B.FI_CONTRACT_CODE WHERE VERSION_NO = L_VERSION_NO AND REPORTING_PERIOD = L_REPORTING_PERIOD AND B.FI_SUBJECT_CODE = L_LINK.FI_SECONDARY_CODE
      UNION ALL
      SELECT COUNT(1) CNT FROM  CONTRACT_LINKS A JOIN VW_SUBJECT_REPORT B ON A.FI_PRIMARY_CODE = B.FI_SUBJECT_CODE
      JOIN VW_SUBJECT_REPORT C ON A.FI_SECONDARY_CODE = C.FI_SUBJECT_CODE
      JOIN VW_CONTRACT_REPORT D ON A.FI_CONTRACT_CODE = D.FI_CONTRACT_CODE
      WHERE A.RECORD_STATUS != 'D'
      AND B.VERSION_NO = L_VERSION_NO AND B.REPORTING_PERIOD = L_REPORTING_PERIOD AND A.FI_SECONDARY_CODE = L_LINK.FI_SECONDARY_CODE
      UNION ALL
      SELECT COUNT(1) FROM INSTITUTION_OWNER_LINKS A JOIN INSTITUTION_REPORT b on a.INSTITUTION_FI_SUBJECT_CODE = b.FI_SUBJECT_CODE
      join VW_SUBJECT_REPORT c on A.OWNER_FI_SUBJECT_CODE = C.FI_SUBJECT_CODE
      WHERE A.RECORD_STATUS != 'D'
      AND B.VERSION_NO = L_VERSION_NO AND B.REPORTING_PERIOD = L_REPORTING_PERIOD AND A.OWNER_FI_SUBJECT_CODE = L_LINK.FI_SECONDARY_CODE
      ) AA;
      IF L_EXISTS = 0 THEN
        IF SUBSTR(L_LINK.FI_SECONDARY_CODE,1,1) = 'P' THEN
          INSERT INTO PERSONAL_DATA_ERROR (VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
          VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_LINK.FI_SECONDARY_CODE, NULL, 'PRIMARY SUBJECT "'||L_LINK.FI_PRIMARY_CODE||'" IN ANOMALY', P_MAKE_BY, SYSDATE);
          -- REMOVE SECONDARY SUBJECT FROM REPORT TABLE
          DELETE FROM PERSONAL_DATA_REPORT WHERE VERSION_NO = L_VERSION_NO AND REPORTING_PERIOD = L_REPORTING_PERIOD AND FI_SUBJECT_CODE = L_LINK.FI_SECONDARY_CODE;
        ELSE
          INSERT INTO INSTITUTION_ERROR (VERSION_NO, REPORTING_PERIOD, FI_SUBJECT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
          VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_LINK.FI_SECONDARY_CODE, NULL, 'PRIMARY SUBJECT "'||L_LINK.FI_PRIMARY_CODE||'" IN ANOMALY', P_MAKE_BY, SYSDATE);
          -- REMOVE SECONDARY SUBJECT FROM REPORT TABLE
          DELETE FROM INSTITUTION_REPORT WHERE VERSION_NO = L_VERSION_NO AND REPORTING_PERIOD = L_REPORTING_PERIOD AND FI_SUBJECT_CODE = L_LINK.FI_SECONDARY_CODE;
        END IF;
      END IF;

      -- MOVING CONTRACT TO ERROR
      -- FOR INSTALMENT CONTRACT
      SELECT COUNT(1) INTO L_EXISTS FROM INSTALMENT_CONTRACTS WHERE FI_CONTRACT_CODE = L_LINK.FI_CONTRACT_CODE;
      IF L_EXISTS > 0 THEN
        INSERT INTO INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
        VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_LINK.FI_CONTRACT_CODE, NULL, 'PRIMARY SUBJECT "'||L_LINK.FI_PRIMARY_CODE||'" IN ANOMALY', P_MAKE_BY, SYSDATE);
        -- REMOVE CONTRACT FROM REPORT TABLE
        DELETE FROM INSTALMENT_CONTRACT_REPORT WHERE VERSION_NO = L_VERSION_NO AND REPORTING_PERIOD = L_REPORTING_PERIOD AND FI_CONTRACT_CODE = L_LINK.FI_CONTRACT_CODE;
      END IF;
      -- FOR NON INSTALMENT CONTRACT
      SELECT COUNT(1) INTO L_EXISTS FROM NON_INSTALMENT_CONTRACTS WHERE FI_CONTRACT_CODE = L_LINK.FI_CONTRACT_CODE;
      IF L_EXISTS > 0 THEN
        INSERT INTO NON_INSTALMENT_CONTRACT_ERROR (VERSION_NO, REPORTING_PERIOD, FI_CONTRACT_CODE, ERROR_CODE, ERROR_DESCRIPTION, MAKE_BY, MAKE_DATE)
        VALUES (L_VERSION_NO, L_REPORTING_PERIOD, L_LINK.FI_CONTRACT_CODE, NULL, 'PRIMARY SUBJECT "'||L_LINK.FI_PRIMARY_CODE||'" IN ANOMALY', P_MAKE_BY, SYSDATE);
        -- REMOVE CONTRACT FROM REPORT TABLE
        DELETE FROM NON_INSTALMENT_CONTRACT_REPORT WHERE VERSION_NO = L_VERSION_NO AND REPORTING_PERIOD = L_REPORTING_PERIOD AND FI_CONTRACT_CODE = L_LINK.FI_CONTRACT_CODE;
      END IF;
