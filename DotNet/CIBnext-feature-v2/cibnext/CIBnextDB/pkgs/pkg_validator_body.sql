-- VALIDATE ALL
-- ============
PROCEDURE SP_VALIDATE_ALL(P_MAKE_BY IN VARCHAR2)
AS
  L_VERSION_NO NUMBER;
  L_REPORTING_PERIOD DATE;
  L_EXISTS INT;
BEGIN
  SELECT TO_DATE(VALUE,'DD-MON-YYYY') INTO L_REPORTING_PERIOD FROM REPORTING_PARAMETERS WHERE KEY = 'REPORTING_PERIOD';
  SELECT MAX(VERSION_NO)+1 INTO L_VERSION_NO FROM CONTRACT_LINK_REPORT WHERE REPORTING_PERIOD = L_REPORTING_PERIOD;

  INSERT INTO VALIDATOR_LOG (REPORTING_PERIOD, LOG_TIME, MESSAGE) VALUES (L_REPORTING_PERIOD, SYSDATE, 'SP_VALIDATE_ALL STARTED');

  IF L_VERSION_NO IS NULL THEN L_VERSION_NO := 1; END IF;

  DBMS_OUTPUT.PUT_LINE('VALIDATING PERSONAL DATA');
  SP_VALIDATE_PERSON (P_MAKE_BY);
  DBMS_OUTPUT.PUT_LINE('VALIDATING INSTITUTIONS');
  SP_VALIDATE_INSTITUTION (P_MAKE_BY);
  DBMS_OUTPUT.PUT_LINE('VALIDATING OWNER LINKS');
  SP_VALIDATE_OWNER_LINK (P_MAKE_BY);

  DBMS_OUTPUT.PUT_LINE('VALIDATING INSTALMENT CONTRACTS');
  SP_VALIDATE_INST_CONTRACT(P_MAKE_BY);
  DBMS_OUTPUT.PUT_LINE('VALIDATING NON INSTALMENT CONTRACTS');
  SP_VALIDATE_NON_INST_CONTRACT(P_MAKE_BY);
  DBMS_OUTPUT.PUT_LINE('VALIDATING CARD CONTRACTS');
  SP_VALIDATE_CARD_CONTRACT(P_MAKE_BY);
  DBMS_OUTPUT.PUT_LINE('VALIDATING CONTRACT LINKS');
  SP_VALIDATE_CONTRACT_LINK(P_MAKE_BY);

  -- FINAL CLEAN UP

  -- SUBJECT HAS NO LINKS WITH ANY INFORMATION
