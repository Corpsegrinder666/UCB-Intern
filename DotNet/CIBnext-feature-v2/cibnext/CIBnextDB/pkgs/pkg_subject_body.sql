  PROCEDURE SP_PERSON_HIST_INSERT
    (
      FI_SUBJECT_CODE_IN IN VARCHAR2
    )
  AS
    L_VERSION_NO NUMBER
    (
      10
    )
    ;
  BEGIN
    SELECT
      MAX(VERSION_NO)+1
    INTO
      L_VERSION_NO
    FROM
      PERSONAL_DATA_HIST
    WHERE
      FI_SUBJECT_CODE = FI_SUBJECT_CODE_IN;
    IF L_VERSION_NO  IS NULL THEN
      L_VERSION_NO   := 1;
    END IF;
    INSERT
    INTO
      PERSONAL_DATA_HIST
    SELECT
      L_VERSION_NO,
      SYSDATE,
      A.*
    FROM
      PERSONAL_DATA A
    WHERE
      FI_SUBJECT_CODE = FI_SUBJECT_CODE_IN;
  END SP_PERSON_HIST_INSERT;
