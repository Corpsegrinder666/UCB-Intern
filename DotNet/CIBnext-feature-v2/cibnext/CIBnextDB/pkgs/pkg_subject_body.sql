  PROCEDURE SP_OWNER_LINK_INSERT(
      RECORD_TYPE_IN                 VARCHAR2,
      FI_CODE_IN                     VARCHAR2,
      BRANCH_CODE_IN                 VARCHAR2,
      INSTITUTION_FI_SUBJECT_CODE_IN VARCHAR2,
      ROLE_IN                        VARCHAR2,
      OWNER_FI_SUBJECT_CODE_IN       VARCHAR2,
      MAKE_BY_IN                     VARCHAR2,
      MAKE_DATE_IN                   DATE,
      RECORD_STATUS_IN               VARCHAR2 )
  AS
    L_EXISTS INT;
  BEGIN
    SELECT
      COUNT(1)
    INTO
      L_EXISTS
    FROM
      INSTITUTION_OWNER_LINKS A
    WHERE
      A.INSTITUTION_FI_SUBJECT_CODE = INSTITUTION_FI_SUBJECT_CODE_IN
    AND A.OWNER_FI_SUBJECT_CODE     = OWNER_FI_SUBJECT_CODE_IN;
    IF L_EXISTS                    IS NULL THEN
      L_EXISTS                     := 0;
    END IF;
    IF L_EXISTS = 0 THEN
      INSERT
      INTO
        INSTITUTION_OWNER_LINKS
        (
          RECORD_TYPE,
          FI_CODE,
          BRANCH_CODE,
          INSTITUTION_FI_SUBJECT_CODE,
          ROLE,
          OWNER_FI_SUBJECT_CODE,
          MAKE_BY,
          MAKE_DATE,
          RECORD_STATUS
        )
        VALUES
        (
          RECORD_TYPE_IN,
          FI_CODE_IN,
          BRANCH_CODE_IN,
          INSTITUTION_FI_SUBJECT_CODE_IN,
          ROLE_IN,
          OWNER_FI_SUBJECT_CODE_IN,
          MAKE_BY_IN,
          sysdate,
          RECORD_STATUS_IN
        );

      UPDATE
        INSTITUTIONS
      SET
        RECORD_STATUS = 'L'
      WHERE
              FI_SUBJECT_CODE = INSTITUTION_FI_SUBJECT_CODE_IN
          AND RECORD_STATUS = 'R'
          AND FI_SUBJECT_CODE LIKE 'I%';

    ELSE
      SP_OWNER_LINK_UPDATE( RECORD_TYPE_IN, FI_CODE_IN, BRANCH_CODE_IN, INSTITUTION_FI_SUBJECT_CODE_IN, ROLE_IN,
      OWNER_FI_SUBJECT_CODE_IN, MAKE_BY_IN, MAKE_DATE_IN, 'U' );
    END IF;
  END SP_OWNER_LINK_INSERT;
  PROCEDURE SP_OWNER_LINK_HIST_INSERT
    (
      INSTITUTION_FI_SUBJECT_CODE_IN IN VARCHAR2,
      OWNER_FI_SUBJECT_CODE_IN       IN VARCHAR2
    )
  AS
    L_VERSION_NO NUMBER
    (
      10
    )
    ;
  BEGIN
    SELECT
      MAX(VERSION_NO)+1
    INTO
      L_VERSION_NO
    FROM
      INSTITUTION_OWNER_LINKS_HIST A
    WHERE
      A.INSTITUTION_FI_SUBJECT_CODE = INSTITUTION_FI_SUBJECT_CODE_IN
    AND A.OWNER_FI_SUBJECT_CODE     = OWNER_FI_SUBJECT_CODE_IN;
    IF L_VERSION_NO                IS NULL THEN
      L_VERSION_NO                 :=1;
    END IF;
    INSERT
    INTO
      INSTITUTION_OWNER_LINKS_HIST
    SELECT
      L_VERSION_NO,
      SYSDATE,
      A.*
    FROM
      INSTITUTION_OWNER_LINKS A
    WHERE
      A.INSTITUTION_FI_SUBJECT_CODE = INSTITUTION_FI_SUBJECT_CODE_IN
    AND A.OWNER_FI_SUBJECT_CODE     = OWNER_FI_SUBJECT_CODE_IN;
  END SP_OWNER_LINK_HIST_INSERT;
  PROCEDURE SP_OWNER_LINK_UPDATE(
      RECORD_TYPE_IN                 VARCHAR2,
      FI_CODE_IN                     VARCHAR2,
      BRANCH_CODE_IN                 VARCHAR2,
      INSTITUTION_FI_SUBJECT_CODE_IN VARCHAR2,
      ROLE_IN                        VARCHAR2,
      OWNER_FI_SUBJECT_CODE_IN       VARCHAR2,
      MAKE_BY_IN                     VARCHAR2,
      MAKE_DATE_IN                   DATE,
      RECORD_STATUS_IN               VARCHAR2 )
  AS
    P_RECORD_STATUS VARCHAR2(1);
  BEGIN
    SELECT RECORD_STATUS INTO P_RECORD_STATUS FROM INSTITUTION_OWNER_LINKS WHERE INSTITUTION_FI_SUBJECT_CODE = INSTITUTION_FI_SUBJECT_CODE_IN AND OWNER_FI_SUBJECT_CODE = OWNER_FI_SUBJECT_CODE_IN;
    IF P_RECORD_STATUS != 'R' THEN
      SP_OWNER_LINK_HIST_INSERT(INSTITUTION_FI_SUBJECT_CODE_IN, OWNER_FI_SUBJECT_CODE_IN);
      UPDATE
        INSTITUTION_OWNER_LINKS
      SET
        RECORD_TYPE   = RECORD_TYPE_IN,
        FI_CODE       = FI_CODE_IN,
        BRANCH_CODE   = DECODE(BRANCH_CODE_IN,'0000',BRANCH_CODE,BRANCH_CODE_IN),
        ROLE          =ROLE_IN,
        MAKE_BY       = MAKE_BY_IN,
        MAKE_DATE     = sysdate,
        RECORD_STATUS = RECORD_STATUS_IN
      WHERE
        INSTITUTION_FI_SUBJECT_CODE = INSTITUTION_FI_SUBJECT_CODE_IN
      AND OWNER_FI_SUBJECT_CODE     = OWNER_FI_SUBJECT_CODE_IN ;
    END IF;
  END SP_OWNER_LINK_UPDATE;
  PROCEDURE SP_GET_SUBJECT_BY_CONTRACT(
      FI_CONTRACT_CODE IN VARCHAR,
      REF_CURSOR OUT SYS_REFCURSOR )
  AS
    L_SUBJECT_CODE VARCHAR ( 16 ) ;
  BEGIN
    SELECT
      A.SUBJECT_CODE
    INTO
      L_SUBJECT_CODE
    FROM
      (
        SELECT
          FI_SUBJECT_CODE SUBJECT_CODE,
          FI_CONTRACT_CODE CONTRACT_CODE
        FROM
          INSTALMENT_CONTRACTS
        UNION
        SELECT
          FI_SUBJECT_CODE,
          FI_CONTRACT_CODE
        FROM
          NON_INSTALMENT_CONTRACTS
        UNION
        SELECT
          FI_SUBJECT_CODE,
          FI_CONTRACT_CODE
        FROM
          CARD_CONTRACTS
      )
      A
    WHERE
      A.CONTRACT_CODE            = FI_CONTRACT_CODE;
    IF SUBSTR(L_SUBJECT_CODE,1,1)='P' THEN
      SP_GET_PERSON ( L_SUBJECT_CODE,REF_CURSOR) ;
    ELSE
      SP_GET_INSTITUTION(L_SUBJECT_CODE, REF_CURSOR);
    END IF;
  END SP_GET_SUBJECT_BY_CONTRACT;
