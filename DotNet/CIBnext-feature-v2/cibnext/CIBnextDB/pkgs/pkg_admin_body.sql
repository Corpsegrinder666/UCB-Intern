--  User Role Info
  
  PROCEDURE SP_GET_USERROLE_BY_FILTERS(
      EMP_ID_IN      IN NUMBER,
      ROLE_CODE_IN   IN VARCHAR2,
      REF_CURSOR OUT SYS_REFCURSOR) AS
  BEGIN
    OPEN REF_CURSOR FOR 
    SELECT EMPID, ROLE_CODE
    FROM APP_USER_ROLES WHERE 
    EMPID like NVL('%'||EMP_ID_IN||'%', EMPID)
    AND ROLE_CODE like NVL('%'||ROLE_CODE_IN||'%', ROLE_CODE);
  END SP_GET_USERROLE_BY_FILTERS;
  
  PROCEDURE SP_EMPID(
      REF_CURSOR OUT SYS_REFCURSOR)
  AS
  BEGIN
    OPEN REF_CURSOR FOR SELECT EMPID FROM APP_USERS
    WHERE (STATUS = 'A' OR STATUS = 'U');
  END SP_EMPID;
  
  PROCEDURE SP_ROLECODE(
      REF_CURSOR OUT SYS_REFCURSOR)
  AS
  BEGIN
    OPEN REF_CURSOR FOR SELECT ROLE_CODE FROM APP_ROLES
    WHERE (STATUS = 'A' OR STATUS = 'U');
  END SP_ROLECODE;
  
  PROCEDURE SP_USERROLE_INSERT(
      EMP_ID_IN            NUMBER,
      ROLE_CODE_IN         VARCHAR2,
      MAKE_BY_IN           VARCHAR2,
      MAKE_DATE_IN         DATE)
      AS
      TMP_EXIST_ID NUMBER;
  BEGIN
  select COUNT(*) into TMP_EXIST_ID FROM APP_USER_ROLES WHERE EMPID IN (EMP_ID_IN)
  AND ROLE_CODE IN (ROLE_CODE_IN); 
  IF TMP_EXIST_ID <> 0
  THEN
    UPDATE APP_USER_ROLES
      SET
        EMPID = EMP_ID_IN,
        ROLE_CODE = ROLE_CODE_IN ,
        MAKE_BY = MAKE_BY_IN ,
        MAKE_DATE = MAKE_DATE_IN
      WHERE
        EMPID = EMP_ID_IN
        OR ROLE_CODE = ROLE_CODE_IN;
  ELSE 
    INSERT INTO APP_USER_ROLES
        VALUES
        ( EMP_ID_IN,
          ROLE_CODE_IN,
          MAKE_BY_IN,
          MAKE_DATE_IN);
  END IF;  
  END SP_USERROLE_INSERT;
  
  PROCEDURE SP_USERROLE_DELETE(
      EMP_ID_IN            NUMBER,
      ROLE_CODE_IN         VARCHAR2,
      MAKE_BY_IN           VARCHAR2,
      MAKE_DATE_IN         DATE) AS
  BEGIN
    DELETE FROM APP_USER_ROLES
      WHERE
        EMPID = EMP_ID_IN
        AND ROLE_CODE = ROLE_CODE_IN;
  END SP_USERROLE_DELETE;
  
  
