CREATE OR REPLACE PACKAGE BODY PKG_ADMIN AS

--  User Info

  PROCEDURE SP_GET_USERS_BY_FILTERS(
      EMP_ID_IN     IN NUMBER,
      EMP_NAME_IN IN VARCHAR2,
      BRANCH_CODE_IN IN VARCHAR2,
      REF_CURSOR OUT SYS_REFCURSOR) AS
  BEGIN
    OPEN REF_CURSOR FOR SELECT EMPID,
    ADID,
    FULLNAME,
    BRANCH_CODE,
    STATUS FROM APP_USERS WHERE (STATUS = 'A' OR STATUS = 'U') 
    AND BRANCH_CODE like NVL('%'||BRANCH_CODE_IN||'%', BRANCH_CODE)
    AND EMPID like NVL('%'||EMP_ID_IN||'%', EMPID)
    AND FULLNAME like NVL('%'||EMP_NAME_IN||'%', FULLNAME);
  END SP_GET_USERS_BY_FILTERS;
  
  
  PROCEDURE SP_USERINFO_INSERT(
      
      EMP_ID_IN            NUMBER,
      AD_ID_IN             VARCHAR2,
      FULLNAME_IN          VARCHAR2,
      BRANCH_CODE_IN       VARCHAR2,
      STATUS_IN            VARCHAR2,
      AD_IN                VARCHAR2,
      MAKE_BY_IN           VARCHAR2,
      MAKE_DATE_IN         DATE)
      AS
      TMP_EXIST_ID NUMBER;
  BEGIN
  select COUNT(EMPID) into TMP_EXIST_ID FROM APP_USERS WHERE EMPID IN(EMP_ID_IN); 
  IF TMP_EXIST_ID <> 0
  THEN
    UPDATE APP_USERS
      SET
        ADID = AD_ID_IN ,
        FULLNAME = FULLNAME_IN ,
        BRANCH_CODE = BRANCH_CODE_IN ,
--        STATUS = 'U',
        MAKE_BY = MAKE_BY_IN ,
        MAKE_DATE = MAKE_DATE_IN
      WHERE
        EMPID = EMP_ID_IN;
  ELSE 
    INSERT INTO APP_USERS
        VALUES
        ( EMP_ID_IN,
          AD_ID_IN,
          FULLNAME_IN,
          BRANCH_CODE_IN,
          STATUS_IN,
          AD_IN,
          MAKE_BY_IN,
          MAKE_DATE_IN);
  END IF;
    
  END SP_USERINFO_INSERT;
  
  
  PROCEDURE SP_USERINFO_DELETE(
      EMP_ID_IN            NUMBER,
      STATUS_IN            VARCHAR2,
      MAKE_BY_IN           VARCHAR2,
      MAKE_DATE_IN         DATE) AS
  BEGIN
    UPDATE APP_USERS
      SET
        STATUS = STATUS_IN ,
        MAKE_BY = MAKE_BY_IN ,
        MAKE_DATE = MAKE_DATE_IN
      WHERE
        EMPID = EMP_ID_IN;
  END SP_USERINFO_DELETE;
  
