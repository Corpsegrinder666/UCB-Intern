  PROCEDURE SP_INST_CONTRACT_HIST_INSERT
    (
      FI_CONTRACT_CODE_IN IN VARCHAR2
    )
  AS
    L_VERSION_NO NUMBER
    (
      10
    )
    ;
  BEGIN
    SELECT
      MAX(VERSION_NO)+1
    INTO
      L_VERSION_NO
    FROM
      INSTALMENT_CONTRACTS_HIST
    WHERE
      FI_CONTRACT_CODE = FI_CONTRACT_CODE_IN;
    IF L_VERSION_NO   IS NULL THEN
      L_VERSION_NO    := 1;
    END IF;
    INSERT
    INTO
      INSTALMENT_CONTRACTS_HIST
    SELECT
      L_VERSION_NO,
      SYSDATE,
      A.*
    FROM
      INSTALMENT_CONTRACTS A
    WHERE
      FI_CONTRACT_CODE = FI_CONTRACT_CODE_IN;
  END SP_INST_CONTRACT_HIST_INSERT;
