      PRIMARY_NAME_IN   IN VARCHAR2,
      SECONDARY_CODE_IN IN VARCHAR2,
      SECONDARY_NAME_IN IN VARCHAR2,
      CONTRACT_CODE_IN  IN VARCHAR2,
      REF_CURSOR OUT SYS_REFCURSOR)
  AS
  BEGIN
    OPEN REF_CURSOR FOR SELECT A.BRANCH_CODE,
    D.NAME TYPE_OF_LINK,
    A.FI_PRIMARY_CODE,
    B.SUBJECT_NAME PRIMARY_NAME,
    A.FI_SECONDARY_CODE,
    C.SUBJECT_NAME SECONDARY_NAME,
    A.FI_CONTRACT_CODE,
    E.CONTRACT_CATEGORY,
    A.RECORD_STATUS FROM CONTRACT_LINKS A JOIN VW_SUBJECTS B ON A.FI_PRIMARY_CODE = B.FI_SUBJECT_CODE JOIN VW_SUBJECTS C
    ON A.FI_SECONDARY_CODE                                                      = C.FI_SUBJECT_CODE JOIN LOV_LINK_TYPES
    D ON A.TYPE_OF_LINK                                                         = D.CODE JOIN VW_CONTRACTS E ON
    A.FI_CONTRACT_CODE                                                          = E.FI_CONTRACT_CODE
    WHERE
    A.RECORD_STATUS != 'D'
    AND A.BRANCH_CODE = NVL(BRANCH_CODE_IN, A.BRANCH_CODE)
    AND FI_PRIMARY_CODE = NVL(PRIMARY_CODE_IN, FI_PRIMARY_CODE )
    AND FI_SECONDARY_CODE = NVL(SECONDARY_CODE_IN, FI_SECONDARY_CODE)
    AND A.FI_CONTRACT_CODE = NVL(CONTRACT_CODE_IN, A.FI_CONTRACT_CODE)
    AND LOWER(B.SUBJECT_NAME) LIKE NVL('%' ||PRIMARY_NAME_IN ||'%','%') AND LOWER(C.SUBJECT_NAME) LIKE NVL('%' || SECONDARY_NAME_IN ||'%','%') ;
  END SP_GET_CONTRACT_LINKS_FILTERED;
