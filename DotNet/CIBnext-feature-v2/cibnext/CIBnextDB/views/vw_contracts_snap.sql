CREATE OR REPLACE
FORCE EDITIONABLE VIEW VW_CONTRACTS_SNAP
(
	CONTRACT_CATEGORY,
	REPORTING_PERIOD, 
	FI_CONTRACT_CODE,
	FI_SUBJECT_CODE,
	CONTRACT_PHASE,
	DEFAULTER_STATUS,
	RECORD_STATUS,
	UBS_ACCOUNT_NO,
	BRANCH_CODE,
	CONTRACT_STATUS
) AS
SELECT
	'Instalment' contract_category,
	REPORTING_PERIOD, 
	fi_contract_code,
	FI_SUBJECT_CODE,
	CONTRACT_phase,
	DEFAULTER_STATUS,
	record_status,
	UBS_ACCOUNT_NO,
	BRANCH_CODE,
	CONTRACT_STATUS
FROM
	instalment_contracts_snap
UNION
SELECT
	'NonInstalment',
	REPORTING_PERIOD, 
	fi_contract_code,
	FI_SUBJECT_CODE,
	CONTRACT_phase,
	DEFAULTER_STATUS,
	record_status,
	UBS_ACCOUNT_NO,
	BRANCH_CODE,
	CONTRACT_STATUS
FROM
	non_instalment_contracts_snap
UNION
SELECT
	'Card',
	REPORTING_PERIOD, 
	fi_contract_code,
	FI_SUBJECT_CODE,
	CONTRACT_phase,
	DEFAULTER_STATUS,
	record_status,
	NULL,
	BRANCH_CODE,
	CONTRACT_STATUS
FROM
	card_contracts_snap;
